def fuse_text_and_face_emotion(text_emotion: EmotionResult, face_json: dict) -> dict:
    face_available = bool(face_json.get("available"))
    face_reliable = bool(face_json.get("reliable"))
    face_emotion = face_json.get("mapped_plutchik_emotion")
    face_confidence = float(face_json.get("confidence") or 0.0)

    text_json = {
        "emotion": text_emotion.emotion,
        "confidence": round(text_emotion.confidence, 4),
        "reason": text_emotion.reason,
    }

    if not face_available or not face_emotion:
        return {
            "emotion": text_emotion.emotion,
            "confidence": round(text_emotion.confidence, 4),
            "reason": f"Text emotion used because no reliable facial-expression signal was available. Text reason: {text_emotion.reason}",
            "text_emotion": text_json,
            "face_emotion": face_json,
            "agreement": False,
            "fusion_strategy": "text_only_no_face_signal",
        }

    agreement = text_emotion.emotion == face_emotion

    if agreement:
        fused_conf = TEXT_WEIGHT * text_emotion.confidence + FACE_WEIGHT * face_confidence
        return {
            "emotion": text_emotion.emotion,
            "confidence": round(max(text_emotion.confidence, fused_conf), 4),
            "reason": f"Text and facial expression agree on {text_emotion.emotion}.",
            "text_emotion": text_json,
            "face_emotion": face_json,
            "agreement": True,
            "fusion_strategy": "agreement_weighted_boost",
        }

    # Conflict handling: explicit/confident text wins, especially when the user says how they feel.
    if text_emotion.confidence >= 0.75:
        fused_conf = max(0.45, text_emotion.confidence - (0.10 if face_reliable else 0.05))
        return {
            "emotion": text_emotion.emotion,
            "confidence": round(fused_conf, 4),
            "reason": f"Text emotion is confident and conflicts with the face signal, so text is prioritized. Face suggested {face_emotion}.",
            "text_emotion": text_json,
            "face_emotion": face_json,
            "agreement": False,
            "fusion_strategy": "conflict_text_priority",
        }

    # If the text is weak or ambiguous and face is strong, let face guide the response.
    if face_reliable and face_confidence >= 0.70 and text_emotion.confidence < 0.60:
        return {
            "emotion": face_emotion,
            "confidence": round(face_confidence * 0.85, 4),
            "reason": f"Text was ambiguous, while facial expression strongly suggested {face_emotion}.",
            "text_emotion": text_json,
            "face_emotion": face_json,
            "agreement": False,
            "fusion_strategy": "ambiguous_text_face_priority",
        }

    # Mixed/uncertain case: keep text but reduce confidence.
    return {
        "emotion": text_emotion.emotion,
        "confidence": round(max(0.35, text_emotion.confidence * 0.75), 4),
        "reason": f"Text and face signals were mixed. Text is retained cautiously; face suggested {face_emotion}.",
        "text_emotion": text_json,
        "face_emotion": face_json,
        "agreement": False,
        "fusion_strategy": "mixed_cautious_text_priority",
    }


