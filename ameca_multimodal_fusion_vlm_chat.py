def simple_emotion_fallback(transcribed_text: str) -> Optional[EmotionResult]:
    text = transcribed_text.strip().lower()
    greetings = {"hello", "hi", "hey", "good morning", "good afternoon", "good evening"}
    farewells = {"bye", "goodbye", "see you", "see you later", "talk later", "have a good day", "have a nice day"}
    if text.rstrip(".!?") in greetings:
        return EmotionResult("trust", 0.6, "The user is opening a friendly social interaction.")
    if any(phrase in text for phrase in farewells):
        return EmotionResult("trust", 0.7, "The user is closing the conversation politely.")
    if "today's date" in text or "todays date" in text or "what is the date" in text:
        return EmotionResult("anticipation", 0.5, "The user is asking for current date information.")
    return None


def detect_text_emotion(client: Client, transcribed_text: str, facial_emotion_hint: Optional[str] = None) -> EmotionResult:
    fallback = simple_emotion_fallback(transcribed_text)
    if fallback:
        return fallback
    response = client.chat(
        model=MODEL_NAME,
        format="json",
        messages=[
            {"role": "system", "content": "You return valid JSON only."},
            {"role": "user", "content": build_emotion_prompt(transcribed_text, facial_emotion_hint)},
        ],
        stream=False,
        options={"temperature": 0.1, "num_predict": 120, "num_ctx": 2048},
    )
    data = safe_json_extract(response["message"]["content"])
    if not data:
        return EmotionResult("trust", 0.3, "Could not parse model output, so a neutral-social fallback was used.")
    emotion = str(data.get("emotion", "")).strip().lower()
    reason = str(data.get("reason", "")).strip()
    try:
        confidence = float(data.get("confidence", 0.0))
    except Exception:
        confidence = 0.0
    confidence = max(0.0, min(1.0, confidence))
    if emotion not in PLUTCHIK_EMOTIONS:
        return EmotionResult("trust", min(confidence, 0.3), "Invalid emotion returned, so fallback emotion was used.")
    return EmotionResult(emotion, confidence, reason or "Emotion inferred from the transcribed message.")


