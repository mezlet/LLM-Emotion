def check_ollama_available(host: str = OLLAMA_HOST, label: str = "Ollama", max_attempts: int = 10, delay_seconds: float = 1.0) -> None:
    client = Client(host=host)
    for attempt in range(1, max_attempts + 1):
        try:
            client.list()
            print_ts(f"{label} is reachable at {host}.")
            return
        except Exception as exc:
            print_ts(f"{label} not reachable yet, attempt {attempt}/{max_attempts}: {exc}")
            time.sleep(delay_seconds)
    raise RuntimeError(f"Could not connect to {label} at {host} after {max_attempts} attempts.")


def ensure_model_available(model_name: str = MODEL_NAME, host: str = OLLAMA_HOST) -> None:
    if not ALLOW_LOCAL_MODEL_PULL:
        print_ts(f"Using Ollama model '{model_name}' from {host}. Skipping local pull.")
        return
    if not host.startswith("http://127.0.0.1") and not host.startswith("http://localhost"):
        print_ts(f"Remote Ollama host {host}; skipping local CLI pull for {model_name}.")
        return
    result = subprocess.run(["ollama", "list"], capture_output=True, text=True, check=False)
    if model_name not in result.stdout:
        print_ts(f"Model {model_name} not found locally. Pulling it now...")
        subprocess.run(["ollama", "pull", model_name], check=True)


