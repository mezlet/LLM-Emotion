def ask_user_to_spell_name(whisper_model: WhisperModel, silero_model, input_device: Optional[int] = INPUT_DEVICE) -> Optional[str]:
    print()
    print_ts("Please spell your name letter by letter. For example: L E T I C I A.")
    print()
    wav_path = listen_for_utterance_with_silero_vad(input_device, silero_model, "spelled name")
    if not wav_path:
        return None
    try:
        transcript = transcribe_audio(wav_path, whisper_model)
    finally:
        try:
            os.remove(wav_path)
        except OSError:
            pass
    print_ts(f"Raw spelling transcript: {transcript}")
    return clean_spelled_name(transcript)


def generate_introduction_response(client: Client, user_name: str) -> str:
    try:
        response = client.chat(
            model=MODEL_NAME,
            messages=[
                {"role": "system", "content": "You are Ameca, a humanoid social robot. Greet the user warmly in 1 sentence and end with 🙂."},
                {"role": "user", "content": f"My name is {user_name}"},
            ],
            options={"temperature": 0.5, "num_predict": 60, "num_ctx": 1024},
            stream=False,
        )
        return normalize_reply(response["message"]["content"], "trust")
    except Exception:
        return f"Hello {user_name}. I am Ameca. It is nice to meet you. 🙂"


def prompt_for_user_name(client: Client, whisper_model: WhisperModel, silero_model, input_device: Optional[int] = INPUT_DEVICE) -> tuple[str, dict, str]:
    users = load_users()
    spoken_name = ""
    for _attempt in range(2):
        print()
        print_ts("Please say your name. For example: 'My name is Leticia'.")
        print()
        wav_path = listen_for_utterance_with_silero_vad(input_device, silero_model, "name")
        if wav_path:
            try:
                spoken_name = transcribe_audio(wav_path, whisper_model).strip()
            finally:
                try:
                    os.remove(wav_path)
                except OSError:
                    pass
        print_ts(f"Raw name transcript: {spoken_name or '(empty)'}")
        extracted_name = extract_name_from_text(spoken_name)
        spoken_name = extracted_name or clean_spoken_name(spoken_name)
        if spoken_name and not looks_like_invalid_name(spoken_name):
            break
        print_ts(f"I heard '{spoken_name or 'nothing'}', but that does not sound like a name.")
    if not spoken_name or looks_like_invalid_name(spoken_name):
        spoken_name = "Guest"
    spelled_name = ask_user_to_spell_name(whisper_model, silero_model, input_device)
    if spelled_name:
        spoken_name = spelled_name
        print_ts(f"Using spelled name: {spoken_name}")
    else:
        print_ts(f"Using spoken name: {spoken_name}")
    print_ts(f"Detected name: {spoken_name}")
    user_key = slugify_name(spoken_name)
    is_new_user = user_key not in users
    if is_new_user:
        users[user_key] = {"name": spoken_name, "created_at": now_ts(), "last_seen": now_ts(), "session_files": [], "conversation_summary": ""}
    else:
        users[user_key]["last_seen"] = now_ts()
    save_users(users)
    print_ts(f"{'Nice to meet you' if is_new_user else 'Welcome back'}, {users[user_key]['name']}.")
    intro = generate_introduction_response(client, users[user_key]["name"])
    print_ts(f"Assistant: {intro}")
    print()
    return user_key, users[user_key], intro


def save_session_transcript(user_key: str, user_profile: dict, session_log: list[dict]) -> str:
    ensure_data_dirs()
    timestamp = datetime.now().strftime("%Y%m%d_%H%M%S")
    path = os.path.join(SESSIONS_DIR, f"{user_key}_{timestamp}.json")
    transcript_data = {
        "user": {"key": user_key, "name": user_profile.get("name", "Guest")},
        "session": {
            "started_at": session_log[0]["timestamp"] if session_log else now_ts(),
            "ended_at": now_ts(),
            "model": MODEL_NAME,
            "ollama_host": OLLAMA_HOST,
            "asr": {"backend": "faster-whisper", **FAST_WHISPER_CONFIG},
            "camera": {
                "backend": "OpenCV/V4L2 or AVFoundation",
                "camera_device": CAMERA_DEVICE,
                "raw_frame_width": CAMERA_FRAME_WIDTH,
                "raw_frame_height": CAMERA_FRAME_HEIGHT,
                "use_zed_half_frame_crop": USE_ZED_HALF_FRAME_CROP,
                "zed_eye": ZED_EYE,
                "preview_enabled": CAMERA_PREVIEW_ENABLED,
            },
            "face_emotion": {"backend": "Ollama vision model", "vision_host": VISION_OLLAMA_HOST, "vision_model": VISION_MODEL_NAME, "max_frames_per_utterance": VISION_MAX_FRAMES_PER_UTTERANCE, "request_timeout_seconds": VISION_REQUEST_TIMEOUT_SECONDS},
            "fusion": {"text_weight": TEXT_WEIGHT, "face_weight": FACE_WEIGHT, "plutchik_emotions": list(PLUTCHIK_EMOTIONS)},
        },
        "messages": session_log,
    }
    with open(path, "w", encoding="utf-8") as file:
        json.dump(transcript_data, file, indent=2, ensure_ascii=False)
    return path


def update_user_after_session(user_key: str, session_path: str) -> None:
    users = load_users()
    if user_key not in users:
        return
    users[user_key]["last_seen"] = now_ts()
    users[user_key].setdefault("session_files", []).append(session_path)
    save_users(users)


def rename_current_user(old_user_key: str, user_profile: dict, new_name: str) -> tuple[str, dict]:
    users = load_users()
    new_name = clean_spoken_name(new_name)
    new_key = slugify_name(new_name)
    if not new_name or looks_like_invalid_name(new_name):
        return old_user_key, user_profile
    if new_key in users:
        users[new_key]["last_seen"] = now_ts()
        save_users(users)
        return new_key, users[new_key]
    old_profile = users.pop(old_user_key, user_profile)
    old_profile["name"] = new_name
    old_profile["last_seen"] = now_ts()
    users[new_key] = old_profile
    save_users(users)
    print_ts(f"Updated user name to: {new_name}")
    return new_key, users[new_key]


