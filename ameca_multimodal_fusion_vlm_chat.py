def get_camera_backend() -> int:
    if sys.platform == "darwin":
        return cv2.CAP_AVFOUNDATION
    if sys.platform.startswith("linux"):
        return cv2.CAP_V4L2
    return cv2.CAP_ANY


def normalize_camera_frame(frame: np.ndarray) -> np.ndarray:
    if USE_ZED_HALF_FRAME_CROP:
        height, width = frame.shape[:2]
        half = width // 2
        if ZED_EYE.lower() == "right":
            frame = frame[:, half:]
        else:
            frame = frame[:, :half]
    return frame


def open_camera(camera_device: Optional[int]) -> cv2.VideoCapture:
    camera_index = 0 if camera_device is None else int(camera_device)
    cap = cv2.VideoCapture(camera_index, get_camera_backend())
    if cap.isOpened():
        # MJPG is usually needed for higher USB camera resolutions through OpenCV/V4L2.
        cap.set(cv2.CAP_PROP_FOURCC, cv2.VideoWriter_fourcc(*"MJPG"))
        cap.set(cv2.CAP_PROP_FRAME_WIDTH, CAMERA_FRAME_WIDTH)
        cap.set(cv2.CAP_PROP_FRAME_HEIGHT, CAMERA_FRAME_HEIGHT)
        cap.set(cv2.CAP_PROP_FPS, 30)
        cap.set(cv2.CAP_PROP_BUFFERSIZE, 1)
        actual_w = int(cap.get(cv2.CAP_PROP_FRAME_WIDTH))
        actual_h = int(cap.get(cv2.CAP_PROP_FRAME_HEIGHT))
        print_ts(f"Using camera device /dev/video{camera_index} at {actual_w}x{actual_h}")
    return cap


def list_camera_devices(max_indices: int = 6) -> None:
    print("\nAvailable camera devices:")
    found = False
    for idx in range(max_indices):
        cap = open_camera(idx)
        try:
            if not cap.isOpened():
                continue
            ok, frame = cap.read()
            if ok and frame is not None:
                norm = normalize_camera_frame(frame)
                found = True
                print(f"[cam {idx}] raw={frame.shape[1]}x{frame.shape[0]} | normalized={norm.shape[1]}x{norm.shape[0]}")
        finally:
            cap.release()
    if not found:
        print("No camera devices found.")
    print()


def encode_frame_as_base64_jpeg(frame_bgr: np.ndarray) -> Optional[str]:
    frame_bgr = normalize_camera_frame(frame_bgr)
    encode_params = [int(cv2.IMWRITE_JPEG_QUALITY), int(VISION_IMAGE_JPEG_QUALITY)]
    ok, buffer = cv2.imencode(".jpg", frame_bgr, encode_params)
    if not ok:
        return None
    return base64.b64encode(buffer).decode("utf-8")


