def main() -> None:
    print_ts("Starting Silero VAD + faster-whisper multimodal Plutchik fusion chat prototype.")
    print_ts(f"Python: {sys.version.split()[0]}")
    print_ts(f"Ollama host: {OLLAMA_HOST}")
    print_ts(f"Ollama model: {MODEL_NAME}")
    print_ts(f"Vision Ollama host: {VISION_OLLAMA_HOST}")
    print_ts(f"Vision model: {VISION_MODEL_NAME}")
    print_ts(f"Camera device: {CAMERA_DEVICE}; ZED half-frame crop: {USE_ZED_HALF_FRAME_CROP}; eye={ZED_EYE}")
    print()

    ensure_data_dirs()
    check_ollama_available(host=OLLAMA_HOST, label="chat Ollama")
    check_ollama_available(host=VISION_OLLAMA_HOST, label="vision Ollama")
    ensure_model_available(MODEL_NAME, host=OLLAMA_HOST)
    ensure_model_available(VISION_MODEL_NAME, host=VISION_OLLAMA_HOST)
    client = Client(host=OLLAMA_HOST)
    vision_client = Client(host=VISION_OLLAMA_HOST, timeout=VISION_REQUEST_TIMEOUT_SECONDS + 2.0)

    list_input_devices()
    list_camera_devices()

    print_ts("Loading Silero VAD...")
    silero_model = load_silero_vad()
    print_ts("Silero VAD ready.")

    print_ts("Loading faster-whisper...")
    whisper_model = WhisperModel(FAST_WHISPER_CONFIG["model"], device=FAST_WHISPER_CONFIG["device"], compute_type=FAST_WHISPER_CONFIG["compute_type"])
    print_ts("faster-whisper ready.")

    user_key, user_profile, intro_reply = prompt_for_user_name(client, whisper_model, silero_model, INPUT_DEVICE)

    print("Automatic listening mode is active.")
    print("Speak naturally. Silero VAD will detect speech, llama3.2-vision:11b will analyze facial emotion, text+face will be fused, and Ameca will respond.")
    print("Say '/exit' or press Ctrl+C to save the transcript and quit.\n")

    history: list[dict] = [{"role": "assistant", "content": intro_reply}]
    session_log: list[dict] = [{"role": "assistant", "content": intro_reply, "timestamp": now_ts(), "intent": "self_introduction"}]

    try:
        while True:
            wav_path, face_capture = listen_for_utterance_with_silero_vad_and_face_emotion(INPUT_DEVICE, silero_model, vision_client, CAMERA_DEVICE, "utterance")

            if face_capture:
                if face_capture.error:
                    print_ts(f"Face emotion capture error: {face_capture.error}")
                else:
                    print_ts(f"Face emotion summary: {face_capture.summary_text}")

            if not wav_path:
                continue
            try:
                user_text = transcribe_audio(wav_path, whisper_model)
            finally:
                try:
                    os.remove(wav_path)
                except OSError:
                    pass

            if not user_text:
                print_ts("No speech detected after transcription.")
                continue

            print_ts(f"faster-whisper transcript: {user_text}")

            maybe_name = extract_name_from_text(user_text)
            if maybe_name and not looks_like_invalid_name(maybe_name):
                user_key, user_profile = rename_current_user(user_key, user_profile, maybe_name)
                reply = generate_introduction_response(client, user_profile["name"])
                print_ts(f"Assistant: {reply}\n")
                history.extend([{"role": "user", "content": user_text}, {"role": "assistant", "content": reply}])
                history = trim_history(history)
                session_log.append({"role": "user", "content": user_text, "timestamp": now_ts(), "intent": "name_introduction"})
                session_log.append({"role": "assistant", "content": reply, "timestamp": now_ts()})
                continue

            command = normalize_command(user_text)
            if command in {"exit", "quit"}:
                print_ts("Goodbye.")
                break
            if command == "clear":
                history.clear()
                print_ts("Conversation history cleared.")
                continue

            facial_hint = face_capture.summary_text if face_capture else None
            face_json = face_capture.as_json if face_capture else default_face_emotion_json()
            text_emotion = detect_text_emotion(client, user_text, facial_hint)
            fused_emotion_json = fuse_text_and_face_emotion(text_emotion, face_json)

            print_ts("Text emotion JSON:")
            print(json.dumps(fused_emotion_json["text_emotion"], indent=2))
            print()
            print_ts("Face emotion JSON:")
            print(json.dumps(face_json, indent=2))
            print()
            print_ts("Fused emotion JSON:")
            print(json.dumps(fused_emotion_json, indent=2))
            print()

            reply = generate_response(client, user_text, fused_emotion_json, history, user_profile)
            print_ts(f"Assistant: {reply}\n")

            user_message = {
                "role": "user",
                "content": user_text,
                "timestamp": now_ts(),
                "text_emotion": fused_emotion_json["text_emotion"],
                "face_emotion": face_json,
                "fused_emotion": fused_emotion_json,
                "facial_emotion_hint": facial_hint,
                "input_mode": "silero_vad_faster_whisper_vlm_multimodal_fusion",
            }
            assistant_message = {"role": "assistant", "content": reply, "timestamp": now_ts()}
            history.extend([{"role": "user", "content": user_text}, {"role": "assistant", "content": reply}])
            history = trim_history(history)
            session_log.extend([user_message, assistant_message])

    except KeyboardInterrupt:
        print()
        print_ts("Goodbye.")
    finally:
        if session_log:
            session_path = save_session_transcript(user_key, user_profile, session_log)
            update_user_after_session(user_key, session_path)
            print_ts(f"Conversation transcript saved to: {session_path}")
        else:
            print_ts("No conversation messages to save.")


if __name__ == "__main__":
    main()
