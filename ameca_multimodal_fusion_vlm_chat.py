@dataclass
class FaceEmotionCapture:
    emotion_score_samples: list[dict[str, float]]
    vlm_result_samples: list[dict]
    frame_count: int
    sampled_frame_count: int
    started_at: str
    ended_at: str
    error: Optional[str] = None

    @property
    def averaged_scores(self) -> dict[str, float]:
        if not self.emotion_score_samples:
            return {}
        totals: dict[str, float] = {}
        for sample in self.emotion_score_samples:
            for emotion, score in sample.items():
                totals[emotion] = totals.get(emotion, 0.0) + float(score)
        count = len(self.emotion_score_samples)
        return {emotion: total / count for emotion, total in totals.items()}

    @property
    def dominant_emotion(self) -> Optional[str]:
        scores = self.averaged_scores
        if not scores:
            return None
        return max(scores.items(), key=lambda item: item[1])[0]

    @property
    def mapped_plutchik_emotion(self) -> Optional[str]:
        dominant = self.dominant_emotion
        if not dominant:
            return None
        return dominant if dominant in PLUTCHIK_EMOTIONS else None

    @property
    def confidence(self) -> float:
        scores = self.averaged_scores
        dominant = self.dominant_emotion
        if not scores or not dominant:
            return 0.0
        return max(0.0, min(1.0, float(scores[dominant]) / 100.0))

    @property
    def is_reliable(self) -> bool:
        scores = self.averaged_scores
        if not scores:
            return False
        ordered = sorted(scores.items(), key=lambda item: item[1], reverse=True)
        top_score = ordered[0][1]
        second_score = ordered[1][1] if len(ordered) > 1 else 0.0
        return top_score >= FACE_MIN_TOP_SCORE and (top_score - second_score) >= FACE_MIN_MARGIN

    @property
    def summary_text(self) -> str:
        if self.error:
            return f"No VLM facial-expression hint available because: {self.error}"
        scores = self.averaged_scores
        if not scores:
            return "No reliable VLM facial-expression hint was captured during speech."
        ordered = sorted(scores.items(), key=lambda item: item[1], reverse=True)
        if not self.is_reliable:
            top_parts = [f"{emo}={score:.0f}%" for emo, score in ordered[:3]]
            return f"VLM facial-expression hint was weak or mixed; top_signals=({', '.join(top_parts)}); samples={self.sampled_frame_count}"
        parts = [f"{emo}={score:.0f}%" for emo, score in ordered if score >= 5.0]
        return f"dominant={self.dominant_emotion}; mapped_plutchik={self.mapped_plutchik_emotion}; averaged_scores=({', '.join(parts)}); samples={self.sampled_frame_count}"

    @property
    def as_json(self) -> dict:
        scores = self.averaged_scores
        return {
            "available": self.error is None and bool(scores),
            "reliable": self.is_reliable,
            "backend": "Ollama vision model",
            "host": VISION_OLLAMA_HOST,
            "model": VISION_MODEL_NAME,
            "dominant_emotion": self.dominant_emotion,
            "mapped_plutchik_emotion": self.mapped_plutchik_emotion,
            "confidence": self.confidence,
            "averaged_scores": scores,
            "vlm_result_samples": self.vlm_result_samples,
            "frame_count": self.frame_count,
            "sampled_frame_count": self.sampled_frame_count,
            "started_at": self.started_at,
            "ended_at": self.ended_at,
            "error": self.error,
            "note": "VLM facial-expression analysis is a secondary signal. Fusion combines it with text emotion.",
        }


