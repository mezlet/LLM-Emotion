def detect_face_region_mediapipe(frame: np.ndarray) -> Optional[dict[str, Any]]:
    """
    Face-bounding-box detection via MediaPipe FaceMesh (ported from
    RRLab's gaze_speaker_utils.py, FaceVerifier/LipLandmarks), used as the
    primary local detector instead of a Haar cascade.

    FaceMesh only reports a match when it can locate genuine facial
    structure (468 3D landmarks across eyes, nose, mouth, jawline), which
    makes it far more resistant to the false positives Haar cascades
    produced on this camera setup (a door handle, background clutter, a
    box spanning most of the frame) while also tending to have better
    recall on off-angle or partially turned faces than a Haar cascade
    tuned strictly enough to avoid those false positives.

    Returns None both when MediaPipe finds no face AND when it errors --
    callers must check _MEDIAPIPE_BROKEN (set here on error) to tell the
    two apart, since only the latter should trigger a Haar fallback.
    """
    global _MEDIAPIPE_BROKEN
    if not HAS_MEDIAPIPE or _MEDIAPIPE_BROKEN:
        return None
    try:
        rgb = cv2.cvtColor(frame, cv2.COLOR_BGR2RGB)
        face_mesh = _get_mediapipe_face_mesh()
        result = face_mesh.process(rgb)
        if not result.multi_face_landmarks:
            return None

        landmarks = result.multi_face_landmarks[0].landmark
        frame_h, frame_w = frame.shape[:2]
        xs = [landmark.x * frame_w for landmark in landmarks]
        ys = [landmark.y * frame_h for landmark in landmarks]
        x1, x2 = min(xs), max(xs)
        y1, y2 = min(ys), max(ys)
        return {
            "x": int(max(0, x1)),
            "y": int(max(0, y1)),
            "w": int(max(1, x2 - x1)),
            "h": int(max(1, y2 - y1)),
        }
    except Exception as exc:
        print_ts(
            f"[WARN] MediaPipe face-region detection failed ({exc}); this "
            "usually means an incompatible mediapipe build/version in this "
            "environment. Disabling MediaPipe for the rest of this run and "
            "falling back to the Haar cascade."
        )
        _MEDIAPIPE_BROKEN = True
        return None


def detect_face_region_local(frame: np.ndarray) -> Optional[dict[str, Any]]:
    """
    Local, in-process face-bounding-box detection, deliberately
    independent of the DeepFace worker subprocess (whose region field was
    confirmed, via saved session JSON, to always come back empty even on
    confident detections).

    Tries MediaPipe FaceMesh first (see detect_face_region_mediapipe()).
    Falls back to the Haar cascade (_detect_face_region_haar()) if
    MediaPipe isn't available/importable, OR if it just errored out for
    the first time this run (_MEDIAPIPE_BROKEN) -- but NOT simply because
    MediaPipe ran successfully and found no face in this particular frame,
    since falling back in that case would reintroduce the false-positive
    classes MediaPipe was chosen to avoid.
    """
    global _MEDIAPIPE_UNAVAILABLE_LOGGED, _MEDIAPIPE_BROKEN
    if HAS_MEDIAPIPE and not _MEDIAPIPE_BROKEN:
        region = detect_face_region_mediapipe(frame)
        if region is not None:
            return region
        if not _MEDIAPIPE_BROKEN:
            return None

    if not _MEDIAPIPE_UNAVAILABLE_LOGGED:
        print_ts("[INFO] Using Haar cascade for face-region detection.")
        _MEDIAPIPE_UNAVAILABLE_LOGGED = True
    return _detect_face_region_haar(frame)


def _face_region_geometry_is_plausible(
    frame: np.ndarray,
    region: Optional[dict[str, Any]],
) -> bool:
    """Reject tiny/invalid regions before they can become calibration crops.

    The warm-up is a controlled, frontal capture where the participant's face
    should occupy a meaningful portion of the frame.  Small square detections
    from background objects can otherwise look face-like to a cascade/FER
    detector.  This check is deliberately geometry-only so it does not add a
    skin-tone-dependent acceptance rule on top of the detector itself.
    """
    if not region:
        return False
    try:
        frame_h, frame_w = frame.shape[:2]
        x = int(region.get("x", -1))
        y = int(region.get("y", -1))
        w = int(region.get("w", 0))
        h = int(region.get("h", 0))
        if x < 0 or y < 0 or w <= 0 or h <= 0:
            return False
        if x >= frame_w or y >= frame_h:
            return False
        if x + w <= 0 or y + h <= 0:
            return False
        aspect = w / float(max(1, h))
        if not (0.60 <= aspect <= 1.60):
            return False
        if h < max(60, int(frame_h * FACE_REGION_MIN_HEIGHT_FRACTION)):
            return False
        area_fraction = (w * h) / float(max(1, frame_w * frame_h))
        if area_fraction > 0.50:
            return False
        return True
    except Exception:
        return False


def _crop_is_large_enough_for_calibration(crop: np.ndarray) -> bool:
    if crop is None or crop.size == 0 or crop.ndim < 2:
        return False
    h, w = crop.shape[:2]
    return min(h, w) >= FACE_CROP_MIN_SIDE_PIXELS


def _detect_face_region_haar(frame: np.ndarray) -> Optional[dict[str, Any]]:
    """
    Fallback face-bounding-box detection via OpenCV's Haar cascade, used
    only when MediaPipe FaceMesh (see detect_face_region_mediapipe()) is
    unavailable or fails to import. Deliberately independent of the
    DeepFace worker subprocess.

    The worker's analyze() responses were confirmed (via saved session
    JSON) to always return an empty region ({}), even on frames where
    DeepFace itself confidently classified an emotion (no_face=False,
    high confidence). Cropping therefore can't rely on that field; this
    detects a face directly in-process instead, on the same frame DeepFace
    already analyzed (or, for baseline capture, on its own -- baseline
    never calls the DeepFace worker at all).

    Sanity filtering: Haar cascades occasionally false-positive on
    background clutter. Three distinct failure modes were observed in
    practice: (1) a large, non-face-shaped box that amounted to saving
    the entire uncropped room; (2) a small, plausibly face-sized box that
    was actually a high-contrast object elsewhere in the room (a door
    handle, a wall clock). (1) is always caught by the maxSize cap plus
    aspect-ratio/area filtering below. (2) is caught by a skin-tone color
    check (see _region_has_skin_tone(), gated behind
    REQUIRE_SKIN_TONE_CONFIRMATION, default ON) -- a much cheaper and
    lower-recall-risk filter than requiring an eye-like feature inside the
    box (see _region_contains_eye(), gated behind REQUIRE_EYE_CONFIRMATION,
    default OFF), since eye cascades proved unreliable enough in practice
    to reject the large majority of genuine faces along with the false
    positives they were meant to catch.
    """
    try:
        frame_h, frame_w = frame.shape[:2]
        gray = cv2.cvtColor(frame, cv2.COLOR_BGR2GRAY)
        cascade = _get_face_cascade()
        faces = cascade.detectMultiScale(
            gray,
            scaleFactor=FACE_CASCADE_SCALE_FACTOR,
            minNeighbors=FACE_CASCADE_MIN_NEIGHBORS,
            flags=cv2.CASCADE_SCALE_IMAGE,
            minSize=FACE_CASCADE_MIN_SIZE,
            maxSize=(int(frame_w * 0.6), int(frame_h * 0.9)),
        )
        if len(faces) == 0:
            return None

        frame_area = float(frame_w * frame_h)
        plausible: list[tuple[int, int, int, int]] = []
        for (x, y, w, h) in faces:
            region = {"x": int(x), "y": int(y), "w": int(w), "h": int(h)}
            if not _face_region_geometry_is_plausible(frame, region):
                continue
            if REQUIRE_SKIN_TONE_CONFIRMATION and not _region_has_skin_tone(
                frame, x, y, w, h, SKIN_TONE_MIN_FRACTION
            ):
                continue
            if REQUIRE_EYE_CONFIRMATION and not _region_contains_eye(gray, x, y, w, h):
                continue
            plausible.append((x, y, w, h))

        if not plausible:
            return None

        x, y, w, h = max(plausible, key=lambda box: box[2] * box[3])
        return {"x": int(x), "y": int(y), "w": int(w), "h": int(h)}
    except Exception as exc:
        print_ts(f"[WARN] Local face-region detection failed: {exc}")
        return None

FACE_CROP_MAX_CANDIDATES_TO_TRY = int(os.environ.get("FACE_CROP_MAX_CANDIDATES_TO_TRY", "6"))


def find_local_face_crops(
    frames: list[np.ndarray],
    max_needed: int,
    max_candidates: int = FACE_CROP_MAX_CANDIDATES_TO_TRY,
    preferred_frame: Optional[np.ndarray] = None,
    preferred_region: Optional[dict[str, Any]] = None,
) -> list[tuple[np.ndarray, dict[str, Any]]]:
    """
    Returns up to max_needed (frame, region) pairs with a usable local
    face-detection region, trying the preferred frame first (e.g.
    DeepFace's already-classified best frame, with its own region if any),
    then the max_candidates sharpest remaining frames in order. Stops as
    soon as max_needed matches are found rather than checking every
    candidate, to avoid unnecessary work once enough crops are in hand.
    """
    found: list[tuple[np.ndarray, dict[str, Any]]] = []

    if preferred_frame is not None:
        # DeepFace may confirm face presence/emotion, but its region is not
        # authoritative for cropping. Re-localize independently.
        region = detect_face_region_local(preferred_frame)
        if region and _face_region_geometry_is_plausible(preferred_frame, region):
            cropped = crop_face(preferred_frame, region)
            if _crop_is_large_enough_for_calibration(cropped):
                found.append((preferred_frame, region))

    if len(found) >= max_needed:
        return found[:max_needed]

    for frame in sorted(frames, key=sharpness, reverse=True)[:max_candidates]:
        if len(found) >= max_needed:
            break
        if preferred_frame is not None and frame is preferred_frame:
            continue
        region = detect_face_region_local(frame)
        if region and _face_region_geometry_is_plausible(frame, region):
            cropped = crop_face(frame, region)
            if _crop_is_large_enough_for_calibration(cropped):
                found.append((frame, region))

    return found[:max_needed]

def find_deepface_confirmed_crops(
    frames: list[np.ndarray],
    deepface: DeepFaceClient,
    max_needed: int,
    max_candidates: int = FACE_CROP_MAX_CANDIDATES_TO_TRY,
    debug_dir: Optional[Path] = None,
    requested_emotion: str = "unknown",
) -> list[tuple[np.ndarray, dict[str, Any]]]:
    """
    Confirms face presence via the DeepFace worker (authoritative: it
    explicitly reports no_face=True/False from its own detector backend,
    rather than us inferring presence from a Haar/MediaPipe box that can
    false-positive on background clutter), then obtains the actual crop
    bounding box via the local detector. DeepFace's own 'region' field was
    confirmed (via saved session JSON) to always come back empty even on
    confident detections, so it can't be used for cropping directly --
    only for confirming a face was found at all.

    Tries the sharpest candidate frames first and stops as soon as
    max_needed DeepFace-confirmed, locally-croppable frames are found.
    """
    found: list[tuple[np.ndarray, dict[str, Any]]] = []
    if not frames:
        return found

    ordered = sorted(frames, key=sharpness, reverse=True)[:max_candidates]
    no_face_count = 0
    failed_count = 0
    no_local_region_count = 0

    for idx, frame in enumerate(ordered):
        if len(found) >= max_needed:
            break

        result = deepface.analyze(frame)
        if result is None:
            failed_count += 1
            if debug_dir is not None:
                _save_debug_frame(
                    frame, debug_dir, f"{requested_emotion}_frame{idx}_failed_or_timeout"
                )
            continue

        if result.no_face or not result.scores:
            no_face_count += 1
            if debug_dir is not None:
                _save_debug_frame(frame, debug_dir, f"{requested_emotion}_frame{idx}_noface")
            continue

        # IMPORTANT: DeepFace's detector and emotion classifier are only the
        # first confirmation.  Do NOT trust result.region directly for warm-up
        # calibration crops: a background object can occasionally be returned
        # as a face region (observed with a wall clock).  Require an independent
        # local face detector to locate the crop on the same DeepFace-positive
        # frame.  It is safer to miss a frame and recapture than to personalize
        # the participant's AU profile from a non-face object.
        region = detect_face_region_local(frame)
        if not region or not _face_region_geometry_is_plausible(frame, region):
            no_local_region_count += 1
            if debug_dir is not None:
                _save_debug_frame(
                    frame, debug_dir,
                    f"{requested_emotion}_frame{idx}_deepface_yes_local_noregion",
                )
            continue

        if debug_dir is not None:
            _save_debug_frame(frame, debug_dir, f"{requested_emotion}_frame{idx}_confirmed")
        found.append((frame, region))

    print_ts(
        f"DeepFace face-presence check for '{requested_emotion}': "
        f"considered={len(ordered)}, confirmed={len(found)}, "
        f"no_face={no_face_count}, failed_or_timeout={failed_count}, "
        f"deepface_yes_but_no_local_region={no_local_region_count}"
    )
    return found

def detect_best_emotion_sample(
    frames: list[np.ndarray],
    deepface: Optional[DeepFaceClient],
    debug_dir: Optional[Path] = None,
    requested_emotion: str = "unknown",
) -> tuple[Optional[np.ndarray], Optional[dict[str, Any]]]:
    """
    Analyze the sharpest candidate frames with DeepFace and pick the most
    confident face+emotion reading. Every candidate frame's outcome is
    logged (and, if VISION_DEBUG, saved to debug_dir tagged with the round
    name, frame index, and outcome) so that a (None, None) result is
    diagnosable instead of silent. Only used for steps 7-9 -- baseline
    rounds (4-6) never call this.

    deepface may be None when facial-expression checking is disabled for
    the session; in that case this immediately returns (None, None)
    without touching the camera frames at all, so callers fall back
    cleanly to text/prosody-only fusion.
    """
    if deepface is None:
        return None, None

    if not frames:
        print_ts(
            "DeepFace: no candidate frames were captured during this "
            "utterance (camera/frame-collector issue?)."
        )
        return None, None

    ordered = sorted(frames, key=sharpness, reverse=True)
    ordered = ordered[:FACE_MAX_CANDIDATE_FRAMES]
    analyzed: list[tuple[np.ndarray, dict[str, Any]]] = []

    no_face_count = 0
    unmapped_count = 0
    failed_count = 0

    for idx, frame in enumerate(ordered):
        result = deepface.analyze(frame)

        if result is None:
            failed_count += 1
            if debug_dir is not None:
                _save_debug_frame(
                    frame, debug_dir, f"{requested_emotion}_frame{idx}_failed_or_timeout"
                )
            continue

        if result.no_face or not result.scores:
            no_face_count += 1
            if debug_dir is not None:
                _save_debug_frame(
                    frame, debug_dir, f"{requested_emotion}_frame{idx}_noface"
                )
            continue

        raw = (
            result.dominant_emotion
            or max(result.scores.items(), key=lambda item: item[1])[0]
        )
        raw = str(raw).strip().lower()
        mapped = DEEPFACE_TO_PROFILE_EMOTION.get(raw)
        if not mapped:
            unmapped_count += 1
            if debug_dir is not None:
                _save_debug_frame(
                    frame, debug_dir, f"{requested_emotion}_frame{idx}_unmapped_{raw}"
                )
            continue

        confidence = float(result.scores.get(raw, 0.0)) / 100.0
        if debug_dir is not None:
            _save_debug_frame(
                frame,
                debug_dir,
                f"{requested_emotion}_frame{idx}_detected-{mapped}_{round(confidence * 100)}pct",
            )

        analyzed.append(
            (
                frame,
                {
                    "emotion": mapped,
                    "deepface_emotion": raw,
                    "confidence": confidence,
                    "scores": result.scores,
                    "region": result.region or {},
                },
            )
        )

    print_ts(
        f"DeepFace candidate frames: considered={len(ordered)}, "
        f"confident={len(analyzed)}, no_face={no_face_count}, "
        f"unmapped={unmapped_count}, failed_or_timeout={failed_count}"
    )

    if not analyzed:
        print_ts(
            "DeepFace did not produce a confident face+emotion reading on any "
            "candidate frame this turn. "
            + (
                f"Check debug frames under: {debug_dir}"
                if debug_dir is not None and VISION_DEBUG
                else "Set VISION_DEBUG=1 to save per-frame debug images."
            )
        )
        return None, None

    best_frame, best_result = max(analyzed, key=lambda item: item[1]["confidence"])
    print_ts(
        f"Best DeepFace reading: emotion={best_result['emotion']} "
        f"confidence={best_result['confidence']:.2f} "
        f"region={best_result.get('region')!r}"
    )
    return best_frame, best_result


