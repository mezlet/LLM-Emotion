def normalize_camera_frame(frame: np.ndarray) -> np.ndarray:
    if USE_ZED_HALF_FRAME_CROP:
        height, width = frame.shape[:2]

        # ZED gives left + right images side by side.
        # Keep only the left camera image.
        frame = frame[:, : width // 2]

    return frame


def get_camera_backend() -> int:
    if sys.platform == "darwin":
        return cv2.CAP_AVFOUNDATION

    if sys.platform.startswith("linux"):
        return cv2.CAP_V4L2

    return cv2.CAP_ANY


def open_camera(camera_device: Optional[int]) -> cv2.VideoCapture:
    candidates = []

    if camera_device is not None:
        candidates.append(camera_device)

    candidates.extend([0, 1, 2, 3])

    seen = set()

    for camera_index in candidates:
        if camera_index in seen:
            continue

        seen.add(camera_index)

        cap = cv2.VideoCapture(camera_index, get_camera_backend())

        if not cap.isOpened():
            cap.release()
            continue

        # MJPG is important for high-resolution ZED over USB.
        cap.set(cv2.CAP_PROP_FOURCC, cv2.VideoWriter_fourcc(*"MJPG"))
        cap.set(cv2.CAP_PROP_FRAME_WIDTH, CAMERA_FRAME_WIDTH)
        cap.set(cv2.CAP_PROP_FRAME_HEIGHT, CAMERA_FRAME_HEIGHT)
        cap.set(cv2.CAP_PROP_FPS, 30)

        time.sleep(0.2)

        ok, frame = cap.read()

        if ok and frame is not None:
            actual_width = int(cap.get(cv2.CAP_PROP_FRAME_WIDTH))
            actual_height = int(cap.get(cv2.CAP_PROP_FRAME_HEIGHT))
            print_ts(
                f"Using camera device /dev/video{camera_index} "
                f"at {actual_width}x{actual_height}"
            )
            return cap

        cap.release()

    return cv2.VideoCapture(-1)


def list_camera_devices(max_indices: int = 6) -> None:
    print("\nAvailable camera devices:")
    found = False

    for idx in range(max_indices):
        cap = open_camera(idx)
        try:
            if not cap.isOpened():
                continue

            ok, frame = cap.read()
            if ok and frame is not None:
                frame = normalize_camera_frame(frame)

            found = True
            width = int(cap.get(cv2.CAP_PROP_FRAME_WIDTH))
            height = int(cap.get(cv2.CAP_PROP_FRAME_HEIGHT))
            print(f"[cam {idx}] available | resolution={width}x{height}")
        finally:
            cap.release()

    if not found:
        print("No camera devices found.")

    print()


def resize_frame_for_vlm(frame_bgr: np.ndarray) -> np.ndarray:
    height, width = frame_bgr.shape[:2]
    if width <= VLM_IMAGE_MAX_WIDTH:
        return frame_bgr

    scale = VLM_IMAGE_MAX_WIDTH / float(width)
    new_size = (VLM_IMAGE_MAX_WIDTH, max(1, int(height * scale)))
    return cv2.resize(frame_bgr, new_size, interpolation=cv2.INTER_AREA)


def encode_frame_as_jpeg_base64(frame_bgr: np.ndarray) -> Optional[str]:
    frame_bgr = resize_frame_for_vlm(frame_bgr)
    ok, encoded = cv2.imencode(
        ".jpg",
        frame_bgr,
        [int(cv2.IMWRITE_JPEG_QUALITY), VLM_JPEG_QUALITY],
    )
    if not ok:
        return None
    return base64.b64encode(encoded.tobytes()).decode("utf-8")


