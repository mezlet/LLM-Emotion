@dataclass
class EmotionResult:
    emotion: str
    confidence: float
    reason: str


@dataclass
class FaceEmotionCapture:
    vlm_results: list[dict]
    frame_count: int
    submitted_frame_count: int
    started_at: str
    ended_at: str
    error: Optional[str] = None

    @property
    def latest_result(self) -> Optional[dict]:
        if not self.vlm_results:
            return None
        return self.vlm_results[-1]

    @property
    def dominant_emotion(self) -> Optional[str]:
        result = self.latest_result
        if not result:
            return None
        emotion = str(result.get("emotion", "")).strip().lower()
        return emotion if emotion in PLUTCHIK_EMOTIONS else None

    @property
    def confidence(self) -> float:
        result = self.latest_result
        if not result:
            return 0.0
        try:
            return max(0.0, min(1.0, float(result.get("confidence", 0.0))))
        except Exception:
            return 0.0

    @property
    def is_reliable(self) -> bool:
        return self.dominant_emotion is not None and self.confidence >= FACE_MIN_TOP_SCORE

    @property
    def summary_text(self) -> str:
        if self.error:
            return f"No facial-expression hint available because: {self.error}"

        result = self.latest_result
        if not result:
            return "No reliable facial-expression hint was captured during speech."

        emotion = self.dominant_emotion or "neutral"
        reason = str(result.get("reason", "")).strip()
        if not self.is_reliable:
            return (
                "Facial-expression hint from VLM was weak or uncertain; "
                f"top_signal={emotion}; confidence={self.confidence:.2f}; "
                f"reason={reason}; samples={self.submitted_frame_count}"
            )

        return (
            f"dominant={emotion}; confidence={self.confidence:.2f}; "
            f"reason={reason}; samples={self.submitted_frame_count}"
        )

    @property
    def as_json(self) -> dict:
        result = self.latest_result or {}
        return {
            "available": self.error is None and bool(result),
            "reliable": self.is_reliable,
            "backend": "ollama_vlm",
            "model": VLM_FACE_MODEL_NAME,
            "dominant_emotion": self.dominant_emotion,
            "confidence": self.confidence,
            "reason": result.get("reason"),
            "raw_result": result,
            "frame_count": self.frame_count,
            "submitted_frame_count": self.submitted_frame_count,
            "started_at": self.started_at,
            "ended_at": self.ended_at,
            "error": self.error,
            "note": (
                "Facial expression analysis is a weak supporting signal only. "
                "Text-based emotion should remain the primary signal."
            ),
        }


