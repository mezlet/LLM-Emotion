class VLMFaceEmotionWorker:
    """Background Ollama VLM worker.

    The audio/VAD loop calls submit_frame() and never waits for Qwen2.5-VL.
    The worker keeps only the newest frame, so slow VLM inference cannot build a
    latency backlog. The final turn uses the latest completed VLM result, if one
    is available; otherwise it safely falls back to no facial-expression hint.
    """

    def __init__(self, host: str, model_name: str) -> None:
        self.host = host
        self.model_name = model_name
        self.input_queue: queue.Queue[Optional[np.ndarray]] = queue.Queue(maxsize=VLM_FACE_QUEUE_SIZE)
        self.result_queue: queue.Queue[dict] = queue.Queue(maxsize=VLM_RESULT_QUEUE_SIZE)
        self.stop_event = threading.Event()
        self.thread = threading.Thread(target=self._run, name="vlm-face-emotion-worker", daemon=True)

    def start(self) -> None:
        if not self.thread.is_alive():
            self.thread.start()
            print_ts(f"Started non-blocking VLM face-emotion worker with {self.model_name}.")

    def stop(self) -> None:
        self.stop_event.set()
        self._replace_pending_frame(None)
        self.thread.join(timeout=2.0)

    def submit_frame(self, frame_bgr: np.ndarray) -> None:
        # Copy now because OpenCV may reuse frame memory later.
        self._replace_pending_frame(frame_bgr.copy())

    def get_latest_result(self) -> Optional[dict]:
        latest = None
        while True:
            try:
                latest = self.result_queue.get_nowait()
            except queue.Empty:
                break
        return latest

    def _replace_pending_frame(self, frame: Optional[np.ndarray]) -> None:
        try:
            while True:
                self.input_queue.get_nowait()
        except queue.Empty:
            pass

        try:
            self.input_queue.put_nowait(frame)
        except queue.Full:
            pass

    def _put_result(self, result: dict) -> None:
        try:
            if self.result_queue.full():
                self.result_queue.get_nowait()
            self.result_queue.put_nowait(result)
        except queue.Empty:
            pass

    def _run(self) -> None:
        client = Client(host=self.host)
        prompt = build_vlm_face_emotion_prompt()

        while not self.stop_event.is_set():
            try:
                frame = self.input_queue.get(timeout=0.1)
            except queue.Empty:
                continue

            if frame is None:
                continue

            started = now_ts()
            try:
                image_b64 = encode_frame_as_jpeg_base64(frame)
                if not image_b64:
                    continue

                response = client.chat(
                    model=self.model_name,
                    format="json",
                    messages=[
                        {
                            "role": "user",
                            "content": prompt,
                            "images": [image_b64],
                        }
                    ],
                    stream=False,
                    options={
                        "temperature": 0.0,
                        "num_predict": 80,
                        "num_ctx": 1024,
                    },
                )

                raw = response["message"]["content"]
                data = safe_json_extract(raw) or {}
                emotion = str(data.get("emotion", "neutral")).strip().lower()
                if emotion not in PLUTCHIK_EMOTIONS:
                    emotion = "neutral"

                try:
                    confidence = max(0.0, min(1.0, float(data.get("confidence", 0.0))))
                except Exception:
                    confidence = 0.0

                self._put_result({
                    "emotion": emotion,
                    "confidence": confidence,
                    "reason": str(data.get("reason", "")).strip(),
                    "started_at": started,
                    "ended_at": now_ts(),
                    "backend": "ollama_vlm",
                    "model": self.model_name,
                })

            except Exception as exc:
                self._put_result({
                    "emotion": "neutral",
                    "confidence": 0.0,
                    "reason": f"VLM face-emotion inference failed: {exc}",
                    "started_at": started,
                    "ended_at": now_ts(),
                    "backend": "ollama_vlm",
                    "model": self.model_name,
                    "error": str(exc),
                })


class FaceEmotionSampler:
    def __init__(self, camera_device: Optional[int], vlm_worker: Optional[VLMFaceEmotionWorker]) -> None:
        self.camera_device = camera_device
        self.vlm_worker = vlm_worker
        self.cap: Optional[cv2.VideoCapture] = None
        self.window_created = False
        self.started_at = now_ts()
        self.error: Optional[str] = None
        self.vlm_results: list[dict] = []
        self.frame_count = 0
        self.submitted_frame_count = 0
        self.capture_start_time: Optional[float] = None
        self.last_sample_time = 0.0
        self.last_status = "warming up..."

    def start(self) -> None:
        self.started_at = now_ts()
        self.capture_start_time = time.time()

        if self.vlm_worker is None:
            self.error = "VLM face-emotion worker is not available."
            return

        self.cap = open_camera(self.camera_device)

        if not self.cap.isOpened():
            self.error = "Could not open camera."
            self.cap.release()
            self.cap = None
            return

        if CAMERA_PREVIEW_ENABLED:
            try:
                cv2.namedWindow(CAMERA_PREVIEW_WINDOW_NAME, cv2.WINDOW_NORMAL)
                self.window_created = True
            except Exception as exc:
                self.error = f"Camera preview could not start: {exc}"

    def sample_if_due(self) -> None:
        if self.vlm_worker is not None:
            latest = self.vlm_worker.get_latest_result()
            if latest:
                self.vlm_results.append(latest)
                emotion = latest.get("emotion", "neutral")
                confidence = float(latest.get("confidence", 0.0) or 0.0)
                self.last_status = f"{emotion}: {confidence:.2f}"

        if self.cap is None or self.capture_start_time is None:
            return

        ok, frame = self.cap.read()
        if not ok or frame is None:
            return

        frame = normalize_camera_frame(frame)

        self.frame_count += 1
        now = time.time()
        elapsed = now - self.capture_start_time

        if CAMERA_PREVIEW_ENABLED and self.window_created:
            try:
                preview_frame = frame.copy()
                cv2.putText(
                    preview_frame,
                    "Recording speech...",
                    (20, 35),
                    cv2.FONT_HERSHEY_SIMPLEX,
                    0.8,
                    (0, 255, 0),
                    2,
                    cv2.LINE_AA,
                )
                cv2.putText(
                    preview_frame,
                    f"VLM emotion: {self.last_status}",
                    (20, 70),
                    cv2.FONT_HERSHEY_SIMPLEX,
                    0.7,
                    (255, 255, 255),
                    2,
                    cv2.LINE_AA,
                )
                cv2.putText(
                    preview_frame,
                    state_display_text(),
                    (20, 105),
                    cv2.FONT_HERSHEY_SIMPLEX,
                    0.7,
                    (255, 255, 255),
                    2,
                    cv2.LINE_AA,
                )
                preview_frame = cv2.resize(
                    preview_frame,
                    (CAMERA_PREVIEW_WIDTH, CAMERA_PREVIEW_HEIGHT),
                )
                cv2.imshow(CAMERA_PREVIEW_WINDOW_NAME, preview_frame)
                cv2.waitKey(1)
            except Exception as exc:
                self.error = f"Camera preview failed: {exc}"

        should_sample = (
            elapsed >= CAMERA_WARMUP_SECONDS
            and now - self.last_sample_time >= CAMERA_SAMPLE_EVERY_SECONDS
        )

        if not should_sample:
            return

        self.last_sample_time = now
        self.submitted_frame_count += 1

        # Non-blocking: submit and immediately return to audio/VAD processing.
        self.vlm_worker.submit_frame(frame)
        self.last_status = "submitted frame to VLM"

    def finish(self) -> FaceEmotionCapture:
        if self.vlm_worker is not None:
            latest = self.vlm_worker.get_latest_result()
            if latest:
                self.vlm_results.append(latest)

        if self.cap is not None:
            self.cap.release()
            self.cap = None

        if self.window_created:
            try:
                cv2.destroyWindow(CAMERA_PREVIEW_WINDOW_NAME)
                cv2.waitKey(1)
            except Exception:
                pass

        return FaceEmotionCapture(
            vlm_results=self.vlm_results,
            frame_count=self.frame_count,
            submitted_frame_count=self.submitted_frame_count,
            started_at=self.started_at,
            ended_at=now_ts(),
            error=self.error,
        )


