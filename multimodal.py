def main() -> None:
    print_ts("Starting Silero VAD + faster-whisper Plutchik chat prototype with local memory.")
    print_ts(f"Python: {sys.version.split()[0]}")
    print_ts(f"Ollama host: {OLLAMA_HOST}")
    print_ts(f"Ollama response model: {MODEL_NAME}")
    print_ts(f"Ollama VLM face model: {VLM_FACE_MODEL_NAME}")
    print()

    ensure_data_dirs()

    check_ollama_available()
    ensure_model_available(MODEL_NAME)
    ensure_model_available(VLM_FACE_MODEL_NAME)

    client = Client(host=OLLAMA_HOST)

    global VLM_FACE_WORKER
    VLM_FACE_WORKER = VLMFaceEmotionWorker(host=OLLAMA_HOST, model_name=VLM_FACE_MODEL_NAME)
    VLM_FACE_WORKER.start()

    list_input_devices()

    print_ts("Loading Silero VAD...")
    try:
        silero_model = load_silero_vad()
        print_ts("Silero VAD ready.")
    except Exception as exc:
        raise RuntimeError(
            "Failed to load Silero VAD. Install it with:\n"
            "pip install silero-vad torch\n\n"
            f"Original error: {exc}"
        )

    print_ts("Loading faster-whisper...")
    try:
        whisper_model = SafeWhisperTranscriber(FAST_WHISPER_CONFIG)

    except Exception as exc:
        # If CUDA model loading itself fails, try CPU/int8 before giving up.
        if FAST_WHISPER_CONFIG.get("device") != "cpu" and ENABLE_WHISPER_CPU_FALLBACK_ON_OOM:
            print_ts(f"Could not load faster-whisper on CUDA: {exc}")
            print_ts("Trying CPU/int8 fallback for faster-whisper...")
            fallback_config = dict(FAST_WHISPER_CONFIG)
            fallback_config["model"] = WHISPER_CPU_FALLBACK_MODEL
            fallback_config["device"] = "cpu"
            fallback_config["compute_type"] = "int8"
            whisper_model = SafeWhisperTranscriber(fallback_config)
        else:
            raise RuntimeError(
                f"Failed to load faster-whisper with active config:\n"
                f"{json.dumps(FAST_WHISPER_CONFIG, indent=2)}\n\n"
                "Install it with:\n"
                "pip install faster-whisper\n\n"
                f"Original error: {exc}"
            )

    user_key, user_profile, intro_reply = prompt_for_user_name(
        client=client,
        whisper_model=whisper_model,
        silero_model=silero_model,
        input_device=INPUT_DEVICE,
    )

    print()

    if user_profile.get("conversation_summary"):
        print_ts("Loaded previous conversation memory.")
        print()

    print("Conversation mode is active.")
    print("After Ameca replies, speak when the terminal shows 'You:'.")
    print("Say '/exit' or press Ctrl+C to save the transcript and quit.")
    print()
    hand_turn_back_to_user()
    print()

    history: list[dict] = []
    session_log: list[dict] = []

    # Store the generated introduction in the transcript so the session is complete.
    session_log.append({
        "role": "ameca",
        "content": intro_reply,
        "timestamp": now_ts(),
        "intent": "self_introduction",
    })
    history.append({"role": "ameca", "content": intro_reply})

    try:
        while True:
            wav_path, face_capture = listen_for_utterance_with_silero_vad_and_face_emotion(
                input_device=INPUT_DEVICE,
                silero_model=silero_model,
                camera_device=CAMERA_DEVICE,
                vlm_worker=VLM_FACE_WORKER,
                prompt_label="utterance",
                announce_feedback=False,
            )

            if face_capture:
                if face_capture.error:
                    print_ts(f"Face emotion capture error: {face_capture.error}")
                else:
                    print_ts(f"Face emotion summary: {face_capture.summary_text}")

            if not wav_path:
                continue

            try:
                user_text = transcribe_audio(wav_path, whisper_model)
            except RuntimeError as exc:
                print_ts(f"Transcription failed but the session will continue: {exc}")
                user_text = ""
            finally:
                try:
                    os.remove(wav_path)
                except OSError:
                    pass

            if not user_text:
                print_ts("No speech detected after transcription.")
                print()
                print("You:")
                print()
                continue

            print_ts(f"faster-whisper transcript: {user_text}")

            maybe_name = extract_name_from_text(user_text)
            if maybe_name and not looks_like_invalid_name(maybe_name):
                user_key, user_profile = rename_current_user(
                    old_user_key=user_key,
                    user_profile=user_profile,
                    new_name=maybe_name,
                )

                reply = generate_introduction_response(
                    client=client,
                    user_name=user_profile["name"],
                )

                set_conversation_state(ConversationState.SPEAKING)
                print_ts(f"Ameca: {reply}")
                hand_turn_back_to_user()
                print()

                history.append({"role": "user", "content": user_text})
                history.append({"role": "ameca", "content": reply})
                history = trim_history(history)

                session_log.append({
                    "role": "user",
                    "content": user_text,
                    "timestamp": now_ts(),
                    "input_mode": "silero_vad_faster_whisper",
                    "intent": "name_introduction",
                })
                session_log.append({
                    "role": "ameca",
                    "content": reply,
                    "timestamp": now_ts(),
                })

                continue

            command = normalize_command(user_text)

            if command in {"exit", "quit"}:
                print_ts("Goodbye.")
                break

            if command == "clear":
                history.clear()
                print_ts("Conversation history cleared.")
                continue

            facial_hint = face_capture.summary_text if face_capture else None
            face_emotion_json = face_capture.as_json if face_capture else default_face_emotion_json()

            emotion_result = detect_emotion(
                client=client,
                transcribed_text=user_text,
                facial_emotion_hint=facial_hint,
            )

            emotion_json = {
                "emotion": emotion_result.emotion,
                "confidence": emotion_result.confidence,
                "reason": emotion_result.reason,
            }

            print_ts("Detected emotion JSON:")
            print(json.dumps(emotion_json, indent=2))
            print()

            print_ts("Face emotion JSON:")
            print(json.dumps(face_emotion_json, indent=2))
            print()

            reply = generate_response(
                client=client,
                user_text=user_text,
                emotion_result=emotion_result,
                history=history,
                user_profile=user_profile,
                face_emotion_json=face_emotion_json,
            )

            set_conversation_state(ConversationState.SPEAKING)
            print_ts(f"Ameca: {reply}")
            hand_turn_back_to_user()
            print()

            user_message = {
                "role": "user",
                "content": user_text,
                "timestamp": now_ts(),
                "emotion": emotion_json,
                "facial_emotion_hint": facial_hint,
                "face_emotion": face_emotion_json,
                "input_mode": "silero_vad_faster_whisper_ollama_vlm",
            }

            assistant_message = {
                "role": "ameca",
                "content": reply,
                "timestamp": now_ts(),
            }

            history.append({"role": "user", "content": user_text})
            history.append({"role": "ameca", "content": reply})
            history = trim_history(history)

            session_log.append(user_message)
            session_log.append(assistant_message)

    except KeyboardInterrupt:
        print()
        print_ts("Goodbye.")

    finally:
        if VLM_FACE_WORKER is not None:
            VLM_FACE_WORKER.stop()

        if session_log:
            session_path = save_session_transcript(
                user_key=user_key,
                user_profile=user_profile,
                session_log=session_log,
            )

            update_user_after_session(
                client=client,
                user_key=user_key,
                session_path=session_path,
                session_log=session_log,
            )

            print_ts(f"Conversation transcript saved to: {session_path}")
        else:
            print_ts("No conversation messages to save.")


if __name__ == "__main__":
    main()
