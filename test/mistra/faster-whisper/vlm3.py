EMOTION_ALIASES = {
    "happy":"joy","happiness":"joy","smile":"joy","smiling":"joy",
    "neutral":"trust","calm":"trust","friendly":"trust","relaxed":"trust",
    "concern":"fear","concerned":"fear","anxious":"fear","anxiety":"fear","afraid":"fear",
    "surprised":"surprise","sad":"sadness","unhappy":"sadness",
    "angry":"anger","mad":"anger","annoyed":"anger","disgusted":"disgust",
    "expectant":"anticipation","curious":"anticipation","thinking":"anticipation",
}

def canonical_emotion_name(name: str) -> Optional[str]:
    cleaned = re.sub(r"[^a-zA-Z]+", "", str(name).strip().lower())
    if cleaned in PLUTCHIK_EMOTIONS: return cleaned
    return EMOTION_ALIASES.get(cleaned)

def normalize_plutchik_scores(raw_data: dict) -> Optional[dict[str, float]]:
    if not isinstance(raw_data, dict): return None
    raw_scores = raw_data.get("scores") if isinstance(raw_data.get("scores"), dict) else raw_data
    scores = {emotion: 0.0 for emotion in PLUTCHIK_EMOTIONS}
    if isinstance(raw_scores, dict):
        for key, value in raw_scores.items():
            emotion = canonical_emotion_name(str(key))
            if not emotion: continue
            try: scores[emotion] += max(0.0, float(value))
            except Exception: continue
    total = sum(scores.values())
    if total <= 0:
        dominant = canonical_emotion_name(str(raw_data.get("dominant_emotion", raw_data.get("emotion", ""))))
        if dominant:
            conf  = max(0.05, min(1.0, float(raw_data.get("confidence", 0.55))))
            other = max(0.0, 1.0 - conf) / max(1, len(PLUTCHIK_EMOTIONS) - 1)
            return {e: (conf if e == dominant else other) * 100.0 for e in PLUTCHIK_EMOTIONS}
        return None
    if total <= 1.5:
        return {e: s * 100.0 for e, s in scores.items()}
    return {e: (s / total) * 100.0 for e, s in scores.items()}


def build_qwen_face_prompt() -> str:
    emotions = ", ".join(PLUTCHIK_EMOTIONS.keys())
    return f"""
        You are a careful visual emotion classifier for a real-time human-robot interaction system.

        INPUT
        You may receive one camera frame or multiple consecutive camera frames from the same short moment.
        There is only one target person. Analyze only the target person's visible face.
        If more than one person appears, classify the most central and largest visible face and ignore all others.
        If the same person appears across multiple frames, combine the evidence across frames instead of treating each frame as a different person.

        TASK
        Classify the target person's facial emotion using exactly one of Plutchik's 8 primary emotions:
        {emotions}

        WHAT TO LOOK AT
        Use only visible facial-expression evidence:
        - eyebrows: raised, lowered, drawn together, relaxed, asymmetrical
        - eyes: widened, narrowed, squinting, downcast, relaxed, tense
        - eyelids: heavy, open, tightened, relaxed
        - mouth: smiling, open, compressed, downturned, parted, tense, relaxed
        - cheeks: raised, flat, tense
        - nose/upper lip: wrinkled nose, raised upper lip, sneer
        - jaw/chin: clenched, dropped, slack, tense
        - overall facial tension: soft/relaxed versus tight/strained

        DO NOT USE
        Do not infer emotion from identity, age, gender, ethnicity, clothing, hairstyle, background, lighting, camera angle, pose, or stereotypes.
        Do not identify the person.

        MULTI-FRAME RULES
        When multiple frames are provided:
        - Track the same target face across frames.
        - Prefer expression features that are consistent across frames.
        - Give less weight to frames that are blurry, dark, overexposed, partly occluded, or have motion blur.
        - If the expression changes across frames, classify the emotion that is most frequent or most visually supported.
        - If frames are mixed or weak, lower confidence and use a more even score distribution.
        - Do not average everything into trust. Trust is only valid when the face is genuinely relaxed, soft, socially open, and without tension indicators.

        EMOTION MAPPING GUIDANCE
        - joy: clear smile, raised cheeks, eye crinkles, bright/positive expression
        - trust: relaxed face, soft eyes, slight natural smile or neutral-friendly expression, no visible tension
        - fear: raised brows, widened tense eyes, mouth stretched or corners pulled back, worried/afraid tension
        - surprise: raised brows, wide eyes, open mouth, sudden alert expression without clear fear or joy
        - sadness: downturned mouth, heavy/downcast eyelids, raised inner brows, slack cheeks, subdued expression
        - disgust: wrinkled nose, raised upper lip, sneer, squinting, expression of aversion
        - anger: lowered/furrowed brows, narrowed eyes, compressed lips, clenched jaw, hard stare, visible tension
        - anticipation: alert focused look, slightly raised brows, parted lips, engaged/expectant expression

        COMMON CONFUSIONS
        - A non-smiling face is not automatically trust.
        - A polite social smile in a conversational context → trust, not joy.
        - Joy requires a CLEARLY enthusiastic, delighted, or laughing expression: visible Duchenne smile with SIMULTANEOUS cheek raise AND eye corner wrinkling.
        - A smile alone, without raised cheeks AND crinkling at the outer eye corners, is trust.
        - When uncertain between joy and trust, choose trust.
        - Raised brows + wide eyes + open mouth → surprise unless there is also defensive fear tension.
        - Downcast eyes + raised inner brows + downturned mouth → sadness, not trust.
        - Lowered brows + tight lips + tense jaw → anger, not trust.
        - Slightly raised brows + focused eyes + mild mouth tension → anticipation, not surprise.
        - Nose wrinkle or raised upper lip → disgust.
        - Furrowed brows + compressed mouth + no raised brows → anger, not fear.

        SCORING RULES
        Return a probability distribution over all 8 emotions (each 0.0 to 1.0, sum ≈ 1.0).
        The highest score must match dominant_emotion.
        Use high confidence only when facial cues are clear and consistent.
        If no usable face is visible: dominant_emotion="trust", confidence=0.1, nearly flat distribution.
        - Do not assign 0.0 to more than 4 emotions. Always assign at least 0.03 to each
          remaining emotion to reflect genuine uncertainty in real-world webcam conditions.

        OUTPUT — JSON only, no markdown, no trailing text:
        {{
        "dominant_emotion": "joy | trust | fear | surprise | sadness | disgust | anger | anticipation",
        "scores": {{
            "joy": 0.0, "trust": 0.0, "fear": 0.0, "surprise": 0.0,
            "sadness": 0.0, "disgust": 0.0, "anger": 0.0, "anticipation": 0.0
        }},
        "confidence": 0.0,
        "reason": "Briefly mention the visible facial cues observed."
        }}
        """.strip()


def analyze_frame_emotion_scores(frame_bgr, vision_client) -> Optional[dict[str, float]]:
    image_b64 = encode_frame_for_ollama(frame_bgr)
    if not image_b64: return None
    try:
        resp = vision_client.chat(
            model=VISION_MODEL_NAME, format="json",
            messages=[{"role":"user","content":build_qwen_face_prompt(),"images":[image_b64]}],
            options={"temperature":0.0,"num_predict":500,"num_ctx":8192}, stream=False)
        raw  = resp.get("message",{}).get("content","")
        if VISION_DEBUG: print_ts(f"Qwen2.5-VL raw: {raw[:500]}")
        data = safe_json_extract(raw)
        if not isinstance(data, dict): return None
        return normalize_plutchik_scores(data)
    except Exception as exc:
        print_ts(f"Qwen2.5-VL failed: {exc}")
        return None


def select_temporally_spread_frames(
    candidate_frames: list[tuple[float, np.ndarray]],
    n: int = FACE_MULTI_FRAME_COUNT,
) -> list[np.ndarray]:
    if not candidate_frames: return []
    n = max(1, int(n))
    if len(candidate_frames) <= n:
        return [frame for _, frame in candidate_frames]
    if n == 1:
        return [candidate_frames[len(candidate_frames) // 2][1]]
    indices = np.linspace(0, len(candidate_frames) - 1, num=n, dtype=int).tolist()
    unique: list[int] = []
    for idx in indices:
        if idx not in unique: unique.append(idx)
    return [candidate_frames[idx][1] for idx in unique]


def analyze_multiple_frames_emotion_scores(
    frames_bgr: list[np.ndarray],
    vision_client: Client,
    max_frames: int = FACE_MULTI_FRAME_COUNT,
) -> Optional[dict[str, float]]:
    images_b64 = []
    for frame in frames_bgr[:max(1, max_frames)]:
        b64 = encode_frame_for_ollama(frame)
        if b64: images_b64.append(b64)
    if not images_b64: return None
    try:
        resp = vision_client.chat(
            model=VISION_MODEL_NAME, format="json",
            messages=[{"role":"user","content":build_qwen_face_prompt(),"images":images_b64}],
            options={"temperature":0.0,"num_predict":500,"num_ctx":8192}, stream=False)
        raw  = resp.get("message",{}).get("content","")
        if VISION_DEBUG: print_ts(f"Qwen2.5-VL multi-frame raw: {raw[:500]}")
        data = safe_json_extract(raw)
        if not isinstance(data, dict): return None
        return normalize_plutchik_scores(data)
    except Exception as exc:
        print_ts(f"Qwen2.5-VL multi-frame failed: {exc}")
        return None


class FaceEmotionSampler:
    def __init__(self, camera_device, vision_client):
        self.camera_device    = camera_device
        self.vision_client    = vision_client
        self.cap              = None
        self.window_created   = False
        self.started_at       = now_ts()
        self.error            = None
        self.emotion_score_samples: list[dict[str, float]] = []
        self.frame_count      = 0
        self.sampled_frame_count = 0
        self.capture_start_time  = None
        self.last_sample_time    = 0.0
        self.last_status         = "warming up..."
        self.snapshot_frame      = None
        self.snapshot_taken_at   = None
        self.candidate_frames: list[tuple[float, np.ndarray]] = []

    def start(self):
        self.started_at = now_ts()
        self.capture_start_time = time.time()
        self.cap = open_camera(self.camera_device)
        if not self.cap.isOpened():
            self.error = "Could not open camera."
            self.cap.release(); self.cap = None; return
        if CAMERA_PREVIEW_ENABLED:
            try:
                cv2.namedWindow(CAMERA_PREVIEW_WINDOW_NAME, cv2.WINDOW_NORMAL)
                self.window_created = True
            except Exception as exc:
                self.error = f"Camera preview could not start: {exc}"

    def _draw_preview(self, frame):
        if not (CAMERA_PREVIEW_ENABLED and self.window_created): return
        try:
            pf = frame.copy()
            cv2.putText(pf, "Recording speech...", (20,35), cv2.FONT_HERSHEY_SIMPLEX, 0.8, (0,255,0), 2, cv2.LINE_AA)
            cv2.putText(pf, f"Emotion: {self.last_status}", (20,70), cv2.FONT_HERSHEY_SIMPLEX, 0.7, (255,255,255), 2, cv2.LINE_AA)
            cv2.imshow(CAMERA_PREVIEW_WINDOW_NAME, cv2.resize(pf, (CAMERA_PREVIEW_WIDTH, CAMERA_PREVIEW_HEIGHT)))
            cv2.waitKey(1)
        except Exception as exc:
            self.error = f"Camera preview failed: {exc}"

    def _frame_sharpness(self, frame_bgr):
        try:
            gray = cv2.cvtColor(frame_bgr, cv2.COLOR_BGR2GRAY)
            return float(cv2.Laplacian(gray, cv2.CV_64F).var())
        except Exception: return 0.0

    def sample_if_due(self):
        if self.cap is None or self.capture_start_time is None: return
        ok, frame = self.cap.read()
        if not ok or frame is None: return
        frame = normalize_camera_frame(frame)
        self.frame_count += 1
        now = time.time()
        elapsed = now - self.capture_start_time
        self._draw_preview(frame)
        if elapsed < CAMERA_WARMUP_SECONDS: return
        if self.candidate_frames and now - self.last_sample_time < CAMERA_SAMPLE_EVERY_SECONDS:
            return
        sharpness = self._frame_sharpness(frame)
        self.candidate_frames.append((sharpness, frame.copy()))
        self.last_sample_time = now
        self.snapshot_taken_at = now_ts()
        if len(self.candidate_frames) > FACE_MAX_CANDIDATE_FRAMES:
            self.candidate_frames = self.candidate_frames[-FACE_MAX_CANDIDATE_FRAMES:]
        self.sampled_frame_count = len(self.candidate_frames)
        self.last_status = f"collecting frames ({self.sampled_frame_count}/{FACE_MAX_CANDIDATE_FRAMES})"
        if VISION_DEBUG:
            print_ts(f"Captured facial candidate {self.sampled_frame_count}/{FACE_MAX_CANDIDATE_FRAMES} sharpness={sharpness:.1f}")

    def _analyze_snapshot_now(self):
        if not self.candidate_frames:
            self.last_status = "no frames captured"; return
        ranked   = sorted(self.candidate_frames, key=lambda x: x[0], reverse=True)
        best_sharpness, best_frame = ranked[0]
        self.snapshot_frame = best_frame
        scores = None
        if FACE_ANALYSIS_STRATEGY == "multi_frame":
            selected = select_temporally_spread_frames(self.candidate_frames, n=FACE_MULTI_FRAME_COUNT)
            scores = analyze_multiple_frames_emotion_scores(selected, self.vision_client)
            if scores is None:
                scores = analyze_frame_emotion_scores(self.snapshot_frame, self.vision_client)
        else:
            scores = analyze_frame_emotion_scores(self.snapshot_frame, self.vision_client)
        if not scores:
            self.last_status = "no reliable VLM facial emotion"; return
        top_emotion, top_score = max(scores.items(), key=lambda x: x[1])
        if top_score < FACE_MIN_TOP_SCORE:
            self.last_status = f"weak: {top_emotion}={top_score:.0f}%"; return
        self.emotion_score_samples.append(scores)
        self.last_status = f"{top_emotion}: {top_score:.0f}%"

    def finish(self) -> FaceEmotionCapture:
        if self.cap is not None:
            self.cap.release(); self.cap = None
        if self.window_created:
            try: cv2.destroyWindow(CAMERA_PREVIEW_WINDOW_NAME); cv2.waitKey(1)
            except Exception: pass
        try: self._analyze_snapshot_now()
        except Exception as exc:
            self.error = f"VLM analysis failed: {exc}"; print_ts(self.error)
        return FaceEmotionCapture(
            emotion_score_samples=self.emotion_score_samples,
            frame_count=self.frame_count, sampled_frame_count=self.sampled_frame_count,
            started_at=self.started_at, ended_at=now_ts(), error=self.error,
        )


