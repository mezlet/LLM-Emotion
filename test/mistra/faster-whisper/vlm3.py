def normalize_camera_frame(frame: np.ndarray) -> np.ndarray:
    if USE_ZED_HALF_FRAME_CROP:
        height, width = frame.shape[:2]
        frame = frame[:, : width // 2]
    return frame

def get_camera_backend() -> int:
    if sys.platform == "darwin":     return cv2.CAP_AVFOUNDATION
    if sys.platform.startswith("linux"): return cv2.CAP_V4L2
    return cv2.CAP_ANY

def open_camera(camera_device: Optional[int]) -> cv2.VideoCapture:
    candidates, seen = [], set()
    if camera_device is not None:
        candidates.append(camera_device)
    candidates.extend([0, 1, 2, 3])
    for idx in candidates:
        if idx in seen: continue
        seen.add(idx)
        cap = cv2.VideoCapture(idx, get_camera_backend())
        if not cap.isOpened(): cap.release(); continue
        cap.set(cv2.CAP_PROP_FOURCC, cv2.VideoWriter_fourcc(*"MJPG"))
        cap.set(cv2.CAP_PROP_FRAME_WIDTH,  CAMERA_FRAME_WIDTH)
        cap.set(cv2.CAP_PROP_FRAME_HEIGHT, CAMERA_FRAME_HEIGHT)
        cap.set(cv2.CAP_PROP_FPS, 30)
        time.sleep(0.2)
        ok, frame = cap.read()
        if ok and frame is not None:
            return cap
        cap.release()
    return cv2.VideoCapture(-1)

def resize_keep_aspect(frame_bgr: np.ndarray, max_side: int = VISION_MAX_IMAGE_SIDE) -> np.ndarray:
    h, w = frame_bgr.shape[:2]
    longest = max(h, w)
    if longest <= max_side: return frame_bgr
    scale = max_side / float(longest)
    return cv2.resize(frame_bgr, (max(1,int(w*scale)), max(1,int(h*scale))), interpolation=cv2.INTER_AREA)

def image_quality_metrics(frame_bgr: np.ndarray) -> dict:
    try:
        gray = cv2.cvtColor(frame_bgr, cv2.COLOR_BGR2GRAY)
        return {"brightness": float(np.mean(gray)), "sharpness": float(cv2.Laplacian(gray, cv2.CV_64F).var())}
    except Exception:
        return {"brightness": 0.0, "sharpness": 0.0}

def denoise_frame(frame_bgr):
    if not VISION_DENOISE_ENABLED: return frame_bgr
    try:
        return cv2.fastNlMeansDenoisingColored(
            frame_bgr, None, h=VISION_DENOISE_H, hColor=VISION_DENOISE_H_COLOR,
            templateWindowSize=7, searchWindowSize=21)
    except Exception: return frame_bgr

def enhance_lighting(frame_bgr):
    if not VISION_LIGHTING_ENHANCE_ENABLED: return frame_bgr
    try:
        lab = cv2.cvtColor(frame_bgr, cv2.COLOR_BGR2LAB)
        l, a, b = cv2.split(lab)
        clahe = cv2.createCLAHE(clipLimit=VISION_CLAHE_CLIP_LIMIT, tileGridSize=(8,8))
        return cv2.cvtColor(cv2.merge((clahe.apply(l), a, b)), cv2.COLOR_LAB2BGR)
    except Exception: return frame_bgr

def sharpen_frame(frame_bgr):
    if not VISION_SHARPEN_ENABLED: return frame_bgr
    try:
        blurred = cv2.GaussianBlur(frame_bgr, (0,0), sigmaX=1.0)
        return cv2.addWeighted(frame_bgr, 1.2, blurred, -0.2, 0)
    except Exception: return frame_bgr

def crop_largest_face_or_center(frame_bgr):
    h, w = frame_bgr.shape[:2]
    try:
        gray    = cv2.cvtColor(frame_bgr, cv2.COLOR_BGR2GRAY)
        cascade = cv2.CascadeClassifier(
            os.path.join(cv2.data.haarcascades, "haarcascade_frontalface_default.xml"))
        faces   = cascade.detectMultiScale(gray, scaleFactor=1.1, minNeighbors=4, minSize=(60,60))
        if len(faces) > 0:
            x, y, fw, fh = max(faces, key=lambda b: b[2]*b[3])
            pad = int(max(fw, fh) * 0.65)
            crop = frame_bgr[max(0,y-pad):min(h,y+fh+pad), max(0,x-pad):min(w,x+fw+pad)]
            if crop.size > 0: return resize_keep_aspect(crop)
    except Exception: pass
    side = min(h, w)
    x1, y1 = (w-side)//2, (h-side)//2
    crop = frame_bgr[max(0,y1):y1+side, max(0,x1):x1+side]
    return resize_keep_aspect(crop if crop.size > 0 else frame_bgr)

def preprocess_frame_for_vlm(frame_bgr):
    prep   = crop_largest_face_or_center(frame_bgr)
    before = image_quality_metrics(prep)
    prep   = denoise_frame(prep)
    prep   = enhance_lighting(prep)
    prep   = sharpen_frame(prep)
    prep   = resize_keep_aspect(prep)
    after  = image_quality_metrics(prep)
    return prep, {
        "brightness_before": before.get("brightness",0), "sharpness_before": before.get("sharpness",0),
        "brightness_after":  after.get("brightness",0),  "sharpness_after":  after.get("sharpness",0),
        "width": float(prep.shape[1]), "height": float(prep.shape[0]),
    }

def is_vlm_image_quality_usable(metrics):
    b = metrics.get("brightness_after", 0.0)
    s = metrics.get("sharpness_after",  0.0)
    if b < VISION_MIN_BRIGHTNESS: return False, f"too dark: {b:.1f}"
    if b > VISION_MAX_BRIGHTNESS: return False, f"too bright: {b:.1f}"
    if s < VISION_MIN_SHARPNESS:
        reason = f"soft but still sent: sharpness={s:.1f}"
        if VISION_SKIP_LOW_QUALITY: return False, f"too blurry: {s:.1f}"
        return True, reason
    return True, "ok"

