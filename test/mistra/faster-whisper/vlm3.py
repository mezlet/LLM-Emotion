def build_response_system_prompt(emotion_result, user_profile=None, face_emotion_json=None) -> str:
    memory_ctx = build_user_memory_context(user_profile)
    if face_emotion_json is None: face_emotion_json = default_face_emotion_json()
    text_emotion_json = {
        "emotion": emotion_result.emotion,
        "confidence": emotion_result.confidence,
        "reason": emotion_result.reason,
    }
    return f"""
        {AMECA_SYSTEM_PROMPT}

        {runtime_context()}

        {memory_ctx}
        You are generating Ameca's next conversational response.

        PRIVATE EMOTION CONTEXT — use only for tone control. Do not mention directly.

        Fused emotion (primary signal):
        {json.dumps(text_emotion_json, indent=2)}

        Face/Qwen2.5-VL emotion (secondary supporting signal):
        {json.dumps(face_emotion_json, indent=2)}

        Interpretation rules:
        - The fused emotion is the primary signal. Adjust tone accordingly.
        - Use the facial signal only as a secondary weak supporting hint.
        - Do not mention camera, VLM, facial analysis, detected emotion, or fusion context to the user.
        - Do not say "you look sad", "your face shows", or "I detected".

        Return JSON only in this exact shape:
        {{"reply": "assistant response without emoji", "emoji": "one facial emoji", "tone": "short tone label"}}

        Conversation behavior rules:
        - Always respond like a helpful assistant. Keep responses context-appropriate.
        - Use the private emotion context only to adjust tone.
        - Use conversation history to avoid repeating yourself.
        - Do not greet repeatedly. After the first greeting, respond directly.
        - Do not reintroduce yourself unless the user asks who you are.
        - Never begin with "As Ameca" or "As a humanoid social robot".
        - Use the user's name occasionally, not in every response.
        - Do not give a list of advice unless the user asks for advice.
        - Speak directly and naturally.
        - Keep the response to 1-2 short sentences unless the user asks for detail.
        - If the user asks who can help, suggest: supervisor, co-supervisor, lab colleagues, thesis coordinator, or university writing center.

        Emoji rules:
        - End with exactly one context-appropriate facial emoji.
        - Use only: 🙂 😊 😌 😔 😟 🤔 😮 😢 😠 🤢
        - Emoji must appear only at the end.
        """.strip()

def trim_history(history): return history[-MAX_HISTORY_MESSAGES:]

def generate_response(client, user_text, emotion_result, history, user_profile=None, face_emotion_json=None) -> str:
    det = deterministic_reply_if_applicable(user_text, emotion_result.emotion)
    if det: return det
    system_prompt = build_response_system_prompt(emotion_result, user_profile, face_emotion_json)[:6000]
    messages = [
        {"role": "system", "content": system_prompt},
        *[{"role": i["role"], "content": i["content"]} for i in trim_history(history[-6:])],
        {"role": "user", "content": user_text[:1500]},
    ]
    resp = client.chat(model=MODEL_NAME, messages=messages,
        options={"temperature":0.4,"num_predict":120,"repeat_penalty":1.25,"num_ctx":2048},
        stream=False)
    raw  = resp["message"]["content"]
    data = safe_json_extract(raw)
    if data and isinstance(data, dict):
        reply_text = str(data.get("reply","")).strip()
        emoji      = str(data.get("emoji","")).strip()
        if emoji in {":)",":-)",""}: emoji = PLUTCHIK_EMOTIONS.get(emotion_result.emotion,"🙂")
        return normalize_reply(f"{reply_text} {emoji}", emotion_result.emotion)
    return normalize_reply(raw, emotion_result.emotion)


