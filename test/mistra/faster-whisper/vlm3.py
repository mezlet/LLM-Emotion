# ASR — transcription with word-level confidence
# ══════════════════════════════════════════════════════════════════════════════

def transcribe_with_confidence(wav_path: str, whisper_model: WhisperModel) -> TranscriptionResult:
    """
    Transcribe with faster-whisper and return a TranscriptionResult.
    word_timestamps=True enables per-word probability scores used by
    compute_linguistic_reliability() as the primary confidence signal.
    """
    segments, info = whisper_model.transcribe(
        wav_path,
        language=FAST_WHISPER_CONFIG.get("language"),
        beam_size=int(FAST_WHISPER_CONFIG.get("beam_size", 1)),
        vad_filter=bool(FAST_WHISPER_CONFIG.get("vad_filter", False)),
        condition_on_previous_text=False,
        word_timestamps=True,
    )
    all_segments     = list(segments)
    text_parts       = []
    word_confidences = []
    no_speech_probs  = []
    avg_logprobs     = []

    for seg in all_segments:
        text_parts.append(seg.text.strip())
        no_speech_probs.append(getattr(seg, "no_speech_prob", 0.0))
        avg_logprobs.append(getattr(seg, "avg_logprob", -1.0))
        if seg.words:
            for word in seg.words:
                prob = getattr(word, "probability", None)
                if prob is not None:
                    word_confidences.append(float(prob))

    text = re.sub(r"\s+", " ", " ".join(text_parts)).strip()
    if len(text.split()) <= 1 and len(text) < 3:
        text = ""

    return TranscriptionResult(
        text=text,
        word_confidences=word_confidences,
        no_speech_prob=float(np.mean(no_speech_probs)) if no_speech_probs else 0.0,
        avg_logprob=float(np.mean(avg_logprobs))       if avg_logprobs    else -1.0,
    )

def transcribe_with_faster_whisper(wav_path: str, whisper_model: WhisperModel) -> str:
    """Backward-compatible wrapper — returns text string only."""
    return transcribe_with_confidence(wav_path, whisper_model).text

transcribe_audio = transcribe_with_faster_whisper


# ══════════════════════════════════════════════════════════════════════════════
# Linguistic reliability score
# ══════════════════════════════════════════════════════════════════════════════

def compute_linguistic_reliability(transcription: TranscriptionResult) -> float:
    """
    r_L = mean_word_confidence × length_factor × (1 − no_speech_prob)

    length_factor = min(1, n_words / LINGUISTIC_MIN_WORDS_FOR_FULL_CREDIT)
    Falls back to exp(avg_logprob) when word timestamps unavailable.
    """
    if not transcription.text.strip():
        return 0.0

    if transcription.word_confidences:
        mean_conf = float(np.mean(transcription.word_confidences))
    else:
        lp = transcription.avg_logprob
        mean_conf = float(np.clip(np.exp(lp), 0.0, 1.0)) if lp > -10.0 else 0.40

    n_words       = len(transcription.text.split())
    length_factor = min(1.0, n_words / LINGUISTIC_MIN_WORDS_FOR_FULL_CREDIT)
    speech_factor = max(0.0, 1.0 - transcription.no_speech_prob)

    return float(np.clip(mean_conf * length_factor * speech_factor, 0.0, 1.0))


