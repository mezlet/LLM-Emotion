def get_active_weights(face_available: bool = True) -> dict[str, float]:
    """Normalised weights for active modalities (kept for logging compatibility)."""
    active = {"linguistic": 0.5}
    if face_available:
        active["visual"] = 0.5
    total = sum(active.values())
    return {k: v / total for k, v in active.items()} if total > 0 else {"linguistic": 1.0}

