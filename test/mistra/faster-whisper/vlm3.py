def ensure_data_dirs() -> None:
    os.makedirs(DATA_DIR, exist_ok=True)
    os.makedirs(SESSIONS_DIR, exist_ok=True)

def slugify_name(name: str) -> str:
    name = name.strip().lower()
    name = re.sub(r"[^a-z0-9]+", "_", name)
    return name.strip("_") or "unknown_user"

def load_users() -> dict:
    ensure_data_dirs()
    if not os.path.exists(USERS_FILE):
        return {}
    try:
        with open(USERS_FILE, "r", encoding="utf-8") as f:
            return json.load(f)
    except json.JSONDecodeError:
        return {}

def save_users(users: dict) -> None:
    ensure_data_dirs()
    with open(USERS_FILE, "w", encoding="utf-8") as f:
        json.dump(users, f, indent=2, ensure_ascii=False)

def clean_spoken_name(spoken_name: str) -> str:
    spoken_name = spoken_name.strip()
    for pattern in [r"^my name is\s+", r"^my name's\s+", r"^i am\s+",
                    r"^i'm\s+", r"^this is\s+", r"^it is\s+", r"^it's\s+", r"^call me\s+"]:
        spoken_name = re.sub(pattern, "", spoken_name, flags=re.IGNORECASE).strip()
    spoken_name = re.sub(r"[^a-zA-Z0-9\s\-]", "", spoken_name)
    return spoken_name[:40].strip() or "Guest"

def clean_spelled_name(text: str) -> Optional[str]:
    text = text.upper().strip()
    for pat in [r"\bMY NAME IS\b", r"\bIT IS\b", r"\bIT'S\b", r"\bSPELL(?:ED|ING)?\b"]:
        text = re.sub(pat, "", text)
    text = re.sub(r"[^A-Z\s]", " ", text)
    letters = [p for p in text.split() if len(p) == 1 and p.isalpha()]
    return "".join(letters).title() if len(letters) >= 2 else None

def extract_name_from_text(text: str) -> Optional[str]:
    for pattern in [r"\bmy name is\s+([a-zA-Z][a-zA-Z\s\-]{1,40})",
                    r"\bmy name's\s+([a-zA-Z][a-zA-Z\s\-]{1,40})",
                    r"\bcall me\s+([a-zA-Z][a-zA-Z\s\-]{1,40})"]:
        match = re.search(pattern, text.strip(), flags=re.IGNORECASE)
        if match:
            candidate = clean_spoken_name(match.group(1))
            if 1 <= len(candidate.split()) <= 4:
                return candidate
    return None

def looks_like_invalid_name(name: str) -> bool:
    return name.strip().lower() in {
        "hello","hi","hey","good morning","good afternoon","good evening",
        "yes","no","okay","ok","thanks","thank you","bye","goodbye",
    }

def rename_current_user(old_user_key, user_profile, new_name):
    users     = load_users()
    new_name  = clean_spoken_name(new_name)
    new_key   = slugify_name(new_name)
    if not new_name or looks_like_invalid_name(new_name):
        return old_user_key, user_profile
    existing = users.get(new_key)
    if existing:
        existing["last_seen"] = now_ts()
        save_users(users)
        return new_key, existing
    old_profile = users.pop(old_user_key, user_profile)
    old_profile["name"]      = new_name
    old_profile["last_seen"] = now_ts()
    users[new_key] = old_profile
    save_users(users)
    return new_key, users[new_key]

