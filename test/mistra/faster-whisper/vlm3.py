def listen_for_utterance_with_silero_vad(input_device, silero_model, prompt_label="utterance"):
    input_sr   = get_input_samplerate(input_device)
    block_size = max(1, int(input_sr * 0.05))
    audio_q: queue.Queue[np.ndarray] = queue.Queue()
    vad_it = VADIterator(silero_model, threshold=SILERO_THRESHOLD,
                         sampling_rate=SILERO_SAMPLE_RATE,
                         min_silence_duration_ms=SILERO_MIN_SILENCE_DURATION_MS,
                         speech_pad_ms=SILERO_SPEECH_PAD_MS)
    pre_roll_max = max(1, int((VAD_PRE_ROLL_SECONDS * SILERO_SAMPLE_RATE) / SILERO_CHUNK_SIZE))
    pre_roll, recorded = [], []
    is_recording, speech_started_at = False, None
    leftover = np.array([], dtype=np.float32)

    def cb(indata, frames, t, status): audio_q.put(indata[:,0].copy())

    print_ts(f"Listening automatically for {prompt_label}. Speak when ready. Press Ctrl+C to quit.")
    try:
        sd.check_input_settings(device=input_device, samplerate=input_sr, channels=1, dtype="float32")
        with sd.InputStream(samplerate=input_sr, channels=1, dtype="float32",
                            device=input_device, blocksize=block_size, callback=cb):
            while True:
                try: block = audio_q.get(timeout=0.1)
                except queue.Empty: continue
                b16k     = resample_audio(block, input_sr, SILERO_SAMPLE_RATE)
                combined = np.concatenate([leftover, b16k]).astype(np.float32, copy=False)
                usable   = (len(combined) // SILERO_CHUNK_SIZE) * SILERO_CHUNK_SIZE
                if usable == 0: leftover = combined; continue
                chunks   = combined[:usable].reshape(-1, SILERO_CHUNK_SIZE)
                leftover = combined[usable:]
                for chunk in chunks:
                    chunk = chunk.astype(np.float32, copy=False)
                    if not is_recording:
                        pre_roll.append(chunk.copy())
                        if len(pre_roll) > pre_roll_max: pre_roll.pop(0)
                    else: recorded.append(chunk.copy())
                    ev  = vad_it(torch.from_numpy(chunk), return_seconds=True)
                    now = time.time()
                    if ev:
                        if "start" in ev and not is_recording:
                            is_recording = True; speech_started_at = now
                            recorded = list(pre_roll); recorded.append(chunk.copy()); pre_roll.clear()
                            print(); print_ts("Speech detected. Recording utterance...")
                        if "end" in ev and is_recording:
                            if now - (speech_started_at or now) >= VAD_MIN_UTTERANCE_SECONDS:
                                print_ts("Speech ended. Processing utterance..."); raise StopIteration
                    if is_recording and speech_started_at and now - speech_started_at >= VAD_MAX_UTTERANCE_SECONDS:
                        print_ts("Maximum utterance length reached."); raise StopIteration
    except StopIteration: pass
    except KeyboardInterrupt: raise
    except Exception as exc: print_ts(f"VAD/audio error: {exc}"); return None
    finally:
        try: vad_it.reset_states()
        except Exception: pass
    if not recorded: return None
    return save_audio_to_temp_wav(np.concatenate(recorded).astype(np.float32, copy=False))


