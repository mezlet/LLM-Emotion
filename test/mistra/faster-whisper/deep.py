def build_response_system_prompt(
    emotion_result: EmotionResult,
    face_emotion_json: Optional[dict] = None,
) -> str:
    emoji = PLUTCHIK_EMOTIONS[emotion_result.emotion]

    if face_emotion_json is None:
        face_emotion_json = default_face_emotion_json()

    text_emotion_json = {
        "emotion": emotion_result.emotion,
        "confidence": emotion_result.confidence,
        "reason": emotion_result.reason,
    }

    return f"""
{AMECA_SYSTEM_PROMPT}
{runtime_context()}

PRIVATE EMOTION CONTEXT
This context is for tone control only. Do not mention it directly.

Text/LLM emotion JSON:
{json.dumps(text_emotion_json, indent=2)}

Face/DeepFace emotion JSON:
{json.dumps(face_emotion_json, indent=2)}

Interpretation rules:
- Treat the Text/LLM emotion JSON as the primary emotional signal.
- Treat the Face/DeepFace emotion JSON as a secondary weak supporting signal.
- If both signals agree, you may gently adapt tone more confidently.
- If both signals conflict, trust the text emotion more.
- Do not mention camera, DeepFace, facial analysis, detected emotion, or private emotion context to the user.
- Do not say things like "you look sad", "your face shows", or "I detected".

RESPONSE RULES
- Respond as Ameca, a humanoid social robot.
- Use the private emotion context only to adjust tone.
- Do not say phrases like "your detected emotion", "you seem sad", "trust is present", or "you are anticipating".
- Do not reintroduce yourself unless the user asks who you are.
- Do not mention emotion labels unless the user explicitly asks.
- Do not repeat advice already given in the recent conversation.
- Keep the response to 1-2 short sentences.
- If the user asks who can help, suggest concrete people: supervisor, co-supervisor, lab colleagues, thesis coordinator, or university writing center.
- End with exactly one facial emoji.
- The only emoji you may use is: {emoji}
- Do not use any other emoji.
- Do not use non-facial emoji.
- Emoji must appear only at the end.
""".strip()


def trim_history(history: list[dict], max_messages: int = MAX_HISTORY_MESSAGES) -> list[dict]:
    return history[-max_messages:]


def prompt_ready_history(history: list[dict]) -> list[dict]:
    return [{"role": item["role"], "content": item["content"]} for item in history]


def generate_response(
    client: Client,
    user_text: str,
    emotion_result: EmotionResult,
    history: list[dict],
    face_emotion_json: Optional[dict] = None,
) -> str:
    deterministic = deterministic_reply_if_applicable(user_text, emotion_result.emotion)
    if deterministic:
        return deterministic

    messages = [
        {
            "role": "system",
            "content": build_response_system_prompt(
                emotion_result=emotion_result,
                face_emotion_json=face_emotion_json,
            ),
        },
        *prompt_ready_history(trim_history(history, 4)),
        {
            "role": "user",
            "content": user_text,
        },
    ]

    response = client.chat(
        model=MODEL_NAME,
        messages=messages,
        options={
            "temperature": 0.4,
            "num_predict": 80,
            "repeat_penalty": 1.25,
        },
        stream=False,
    )

    raw_reply = response["message"]["content"]
    return normalize_reply(raw_reply, emotion_result.emotion)


