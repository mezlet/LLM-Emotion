def main() -> None:
    print_ts("Starting multimodal Plutchik + DeepFace Ameca chat prototype.")
    print_ts(f"Python: {sys.version.split()[0]}")
    print_ts(f"Platform: {sys.platform}")
    print_ts(f"Ollama host: {OLLAMA_HOST}")
    print_ts(f"Ollama model: {MODEL_NAME}")
    print()

    check_ollama_available()
    ensure_model_available(MODEL_NAME)

    client = Client(host=OLLAMA_HOST)

    print_ts(
        f"Loading Faster-Whisper profile={FASTER_WHISPER_CONFIG['profile']}, "
        f"model={FASTER_WHISPER_CONFIG['model']}, "
        f"device={FASTER_WHISPER_CONFIG['device']}, "
        f"compute_type={FASTER_WHISPER_CONFIG['compute_type']}..."
    )

    try:
        whisper_model = WhisperModel(
            FASTER_WHISPER_CONFIG["model"],
            device=FASTER_WHISPER_CONFIG["device"],
            compute_type=FASTER_WHISPER_CONFIG["compute_type"],
        )

        print_ts("Faster-Whisper ready.")

    except Exception as exc:
        raise RuntimeError(
            f"Failed to load Faster-Whisper with active config:\n"
            f"{json.dumps(FASTER_WHISPER_CONFIG, indent=2)}\n\n"
            f"Original error: {exc}"
        )

    print()

    print("Commands:")
    print("  /speak   record microphone input, camera preview, and DeepFace emotion hint")
    print("  /devices list available microphones")
    print("  /mic     choose microphone")
    print("  /cams    list available cameras")
    print("  /cam     choose camera")
    print("  /clear   clear conversation history")
    print("  /exit    quit")
    print()

    history: list[dict] = []
    current_input_device = INPUT_DEVICE
    current_camera_device = CAMERA_DEVICE

    while True:
        user_text, current_input_device, current_camera_device, face_capture = get_user_input(
            whisper_model=whisper_model,
            current_input_device=current_input_device,
            current_camera_device=current_camera_device,
        )

        if user_text is None:
            print_ts("Goodbye.")
            break

        if not user_text:
            continue

        command = normalize_command(user_text)

        if command in {"exit", "quit"}:
            print_ts("Goodbye.")
            break

        if command == "clear":
            history.clear()
            print_ts("Conversation history cleared.")
            continue

        facial_hint = face_capture.summary_text if face_capture else None
        face_emotion_json = face_capture.as_json if face_capture else default_face_emotion_json()

        emotion_result = detect_emotion(
            client=client,
            transcribed_text=user_text,
            facial_emotion_hint=facial_hint,
        )

        llm_emotion_json = {
            "emotion": emotion_result.emotion,
            "confidence": emotion_result.confidence,
            "reason": emotion_result.reason,
        }

        print_ts("LLM emotion JSON:")
        print(json.dumps(llm_emotion_json, indent=2))
        print()

        print_ts("Face emotion JSON:")
        print(json.dumps(face_emotion_json, indent=2))
        print()

        reply = generate_response(
            client=client,
            user_text=user_text,
            emotion_result=emotion_result,
            history=history,
            face_emotion_json=face_emotion_json,
        )

        print_ts(f"Assistant: {reply}")
        print()

        history.append({
            "role": "user",
            "content": user_text,
            "facial_emotion_hint": facial_hint,
            "face_emotion_json": face_emotion_json,
            "llm_emotion_json": llm_emotion_json,
        })
        history.append({"role": "assistant", "content": reply})
        history = trim_history(history)


if __name__ == "__main__":
    main()
