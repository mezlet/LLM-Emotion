def analyze_frame_emotion_scores(frame_bgr: np.ndarray) -> Optional[dict[str, float]]:
    try:
        result = DeepFace.analyze(
            img_path=frame_bgr,
            actions=DEEPFACE_ACTIONS,
            enforce_detection=False,
            detector_backend=DEEPFACE_DETECTOR_BACKEND,
            align=DEEPFACE_ALIGN,
            silent=True,
        )

        if isinstance(result, list):
            if not result:
                return None
            result = result[0]

        scores = result.get("emotion")
        if not isinstance(scores, dict):
            return None

        return {emotion: float(score) for emotion, score in scores.items()}

    except Exception:
        return None


def capture_face_emotion_during_recording(
    duration_seconds: int,
    camera_device: Optional[int],
    sample_every_seconds: float = CAMERA_SAMPLE_EVERY_SECONDS,
    stop_event: Optional[threading.Event] = None,
) -> FaceEmotionCapture:
    started_at = now_ts()
    emotion_score_samples: list[dict[str, float]] = []
    frame_count = 0
    sampled_frame_count = 0
    last_status = "warming up..."

    cap = open_camera(camera_device)

    if not cap.isOpened():
        return FaceEmotionCapture(
            emotion_score_samples=[],
            frame_count=0,
            sampled_frame_count=0,
            started_at=started_at,
            ended_at=now_ts(),
            error="Could not open camera.",
        )

    window_created = False

    try:
        end_time = time.time() + duration_seconds
        capture_start_time = time.time()
        last_sample_time = 0.0

        print_ts("Camera emotion capture and preview are active during voice recording.")

        if CAMERA_PREVIEW_ENABLED:
            cv2.namedWindow(CAMERA_PREVIEW_WINDOW_NAME, cv2.WINDOW_NORMAL)
            window_created = True

        while time.time() < end_time:
            if stop_event is not None and stop_event.is_set():
                break

            ok, frame = cap.read()
            if not ok or frame is None:
                time.sleep(0.05)
                continue

            frame_count += 1
            now = time.time()
            elapsed = now - capture_start_time
            remaining = max(0.0, end_time - now)

            if CAMERA_PREVIEW_ENABLED:
                preview_frame = frame.copy()

                cv2.putText(
                    preview_frame,
                    f"Recording... {remaining:.1f}s left",
                    (20, 35),
                    cv2.FONT_HERSHEY_SIMPLEX,
                    0.8,
                    (0, 255, 0),
                    2,
                    cv2.LINE_AA,
                )

                cv2.putText(
                    preview_frame,
                    f"Emotion: {last_status}",
                    (20, 70),
                    cv2.FONT_HERSHEY_SIMPLEX,
                    0.7,
                    (255, 255, 255),
                    2,
                    cv2.LINE_AA,
                )

                preview_frame = cv2.resize(preview_frame, (640, 480))
                cv2.imshow(CAMERA_PREVIEW_WINDOW_NAME, preview_frame)

                key = cv2.waitKey(1) & 0xFF
                if key == ord("q"):
                    if stop_event is not None:
                        stop_event.set()
                    break

            should_sample = (
                elapsed >= CAMERA_WARMUP_SECONDS
                and now - last_sample_time >= sample_every_seconds
            )

            if should_sample:
                last_sample_time = now
                sampled_frame_count += 1

                scores = analyze_frame_emotion_scores(frame)
                if scores:
                    emotion_score_samples.append(scores)
                    top_emotion, top_score = max(scores.items(), key=lambda item: item[1])
                    last_status = f"{top_emotion}: {top_score:.0f}%"
                else:
                    last_status = "no face/emotion detected"

            time.sleep(0.02)

    except Exception as exc:
        return FaceEmotionCapture(
            emotion_score_samples=emotion_score_samples,
            frame_count=frame_count,
            sampled_frame_count=sampled_frame_count,
            started_at=started_at,
            ended_at=now_ts(),
            error=f"Camera preview/capture failed: {exc}",
        )

    finally:
        cap.release()

        if window_created:
            try:
                cv2.destroyWindow(CAMERA_PREVIEW_WINDOW_NAME)
                cv2.waitKey(1)
            except Exception:
                pass

    return FaceEmotionCapture(
        emotion_score_samples=emotion_score_samples,
        frame_count=frame_count,
        sampled_frame_count=sampled_frame_count,
        started_at=started_at,
        ended_at=now_ts(),
        error=None,
    )


def record_audio_and_capture_face_emotion(
    max_seconds: int = MAX_RECORD_SECONDS,
    input_device: Optional[int] = INPUT_DEVICE,
    camera_device: Optional[int] = CAMERA_DEVICE,
) -> Tuple[Optional[str], Optional[FaceEmotionCapture]]:
    """
    Record audio in a background thread.
    Run camera preview/emotion capture on the main thread.

    This is important on macOS because cv2.namedWindow/cv2.imshow
    can crash when called from a worker thread.
    """
    audio_result: dict[str, Optional[str]] = {"wav_path": None}
    stop_event = threading.Event()

    def audio_worker() -> None:
        try:
            audio_result["wav_path"] = record_audio_to_wav(
                max_seconds=max_seconds,
                input_device=input_device,
            )
        finally:
            stop_event.set()

    audio_thread = threading.Thread(target=audio_worker, daemon=False)
    audio_thread.start()

    face_capture = capture_face_emotion_during_recording(
        duration_seconds=max_seconds,
        camera_device=camera_device,
        sample_every_seconds=CAMERA_SAMPLE_EVERY_SECONDS,
        stop_event=stop_event,
    )

    stop_event.set()
    audio_thread.join()

    return audio_result.get("wav_path"), face_capture


