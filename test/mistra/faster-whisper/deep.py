# Input handling
# =========================

def get_user_input(
    whisper_model,
    current_input_device: Optional[int],
    current_camera_device: Optional[int],
) -> tuple[Optional[str], Optional[int], Optional[int], Optional[FaceEmotionCapture]]:

    try:
        user_input = input("You: ").strip()
    except (EOFError, KeyboardInterrupt):
        return None, current_input_device, current_camera_device, None

    if not user_input:
        return "", current_input_device, current_camera_device, None

    command = normalize_command(user_input)

    if command == "devices":
        list_input_devices()
        return "", current_input_device, current_camera_device, None

    if command == "mic":
        return "", choose_input_device(current_input_device), current_camera_device, None

    if command == "cams":
        list_camera_devices()
        return "", current_input_device, current_camera_device, None

    if command == "cam":
        return "", current_input_device, choose_camera_device(current_camera_device), None

    if command == "speak":
        if whisper_model is None:
            print("Voice input is unavailable because Faster-Whisper failed to load.")
            return "", current_input_device, current_camera_device, None

        wav_path, face_capture = record_audio_and_capture_face_emotion(
            max_seconds=MAX_RECORD_SECONDS,
            input_device=current_input_device,
            camera_device=current_camera_device,
        )

        if not wav_path:
            if face_capture:
                if face_capture.error:
                    print_ts(f"Face emotion capture error: {face_capture.error}")
                else:
                    print_ts(f"Face emotion summary: {face_capture.summary_text}")

            return "", current_input_device, current_camera_device, face_capture

        try:
            transcript = transcribe_with_faster_whisper(wav_path, whisper_model)
        finally:
            try:
                os.remove(wav_path)
            except OSError:
                pass

        if transcript:
            print_ts(f"Faster-Whisper transcript: {transcript}")

            if face_capture:
                if face_capture.error:
                    print_ts(f"Face emotion capture error: {face_capture.error}")
                else:
                    print_ts(f"Face emotion summary: {face_capture.summary_text}")

            return transcript, current_input_device, current_camera_device, face_capture

        print("No speech detected.")
        return "", current_input_device, current_camera_device, face_capture

    return user_input, current_input_device, current_camera_device, None


