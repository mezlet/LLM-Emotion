def summarize_session_with_llm(client, session_log, previous_summary="") -> str:
    if not session_log:
        return previous_summary
    compact = [f"{i['role']}: {i['content']}" for i in session_log[-20:]]
    prompt = f"""
Summarize this human-robot conversation for future continuity.

Previous saved summary:
{previous_summary or "None"}

Recent session:
{chr(10).join(compact)}

Return a concise memory summary in 3-6 bullet points.
Include: user's name, main topics, preferences, emotional context.
Do not invent facts.
""".strip()
    try:
        resp = client.chat(
            model=MODEL_NAME,
            messages=[
                {"role": "system", "content": "You summarize conversations accurately."},
                {"role": "user",   "content": prompt},
            ],
            options={"temperature": 0.2, "num_predict": 180, "num_ctx": 2048},
            stream=False,
        )
        return resp["message"]["content"].strip()
    except Exception as exc:
        print_ts(f"Could not summarize session: {exc}")
        return previous_summary

def update_user_after_session(client, user_key, session_path, session_log) -> None:
    users = load_users()
    if user_key not in users:
        return
    users[user_key]["last_seen"] = now_ts()
    users[user_key].setdefault("session_files", []).append(session_path)
    if ENABLE_LLM_SESSION_SUMMARY:
        prev = users[user_key].get("conversation_summary", "")
        users[user_key]["conversation_summary"] = summarize_session_with_llm(
            client, session_log, prev)
    save_users(users)


