def prompt_for_user_name(client, whisper_model, silero_model, input_device=INPUT_DEVICE):
    users, spoken_name = load_users(), ""
    for _ in range(2):
        print_ts("Please say your name.")
        wav = listen_for_utterance_with_silero_vad(input_device, silero_model, "name")
        if wav:
            try: spoken_name = transcribe_with_confidence(wav, whisper_model).text.strip()
            finally:
                try: os.remove(wav)
                except OSError: pass
        extracted = extract_name_from_text(spoken_name)
        spoken_name = extracted or clean_spoken_name(spoken_name)
        if spoken_name and not looks_like_invalid_name(spoken_name): break
        print_ts(f"'{spoken_name or 'nothing'}' does not sound like a name.")
    if not spoken_name or looks_like_invalid_name(spoken_name): spoken_name = "Guest"
    spelled = ask_user_to_spell_name(whisper_model, silero_model, input_device)
    if spelled: spoken_name = spelled
    user_key  = slugify_name(spoken_name)
    is_new    = user_key not in users
    if is_new:
        users[user_key] = {"name": spoken_name, "created_at": now_ts(),
                           "last_seen": now_ts(), "session_files": [], "conversation_summary": ""}
    else:
        users[user_key]["last_seen"] = now_ts()
    save_users(users)
    print_ts(f"{'Nice to meet you' if is_new else 'Welcome back'}, {users[user_key]['name']}.")
    intro = generate_introduction_response(client, users[user_key]["name"])
    print_ts(f"Assistant: {intro}")
    return user_key, users[user_key], intro


