# Emoji / reply normalisation  (unchanged)
# ══════════════════════════════════════════════════════════════════════════════

def remove_all_emojis_except_allowed_faces(text):
    result = []
    for char in text:
        if char in ALLOWED_FACE_EMOJIS: result.append(char); continue
        code = ord(char)
        if (0x1F300 <= code <= 0x1FAFF or 0x2600 <= code <= 0x27BF or code in {0x200D, 0xFE0F}):
            continue
        result.append(char)
    return "".join(result)

def normalize_reply(raw_reply, emotion) -> str:
    required_emoji = PLUTCHIK_EMOTIONS[emotion]
    cleaned = remove_all_emojis_except_allowed_faces(raw_reply)
    cleaned = "".join(c for c in cleaned if c not in ALLOWED_FACE_EMOJIS)
    cleaned = re.sub(r"[:;=8][\-^]?[)(DPp/\\|]+", "", cleaned)
    cleaned = re.sub(r"\s+", " ", cleaned).strip()
    cleaned = re.sub(r"\s+([,.!?;:])", r"\1", cleaned)
    if not cleaned: cleaned = "I'm here with you."
    return f"{cleaned} {required_emoji}"


