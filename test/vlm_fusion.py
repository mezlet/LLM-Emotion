def open_camera(camera_device: Optional[int]) -> cv2.VideoCapture:
    candidates = list({camera_device, 0, 1, 2, 3}) if camera_device is not None else [0, 1, 2, 3]
    for idx in candidates:
        if idx is None:
            continue
        cap = cv2.VideoCapture(idx, get_camera_backend())
        if not cap.isOpened():
            cap.release()
            continue
        cap.set(cv2.CAP_PROP_FOURCC, cv2.VideoWriter_fourcc(*"MJPG"))
        cap.set(cv2.CAP_PROP_FRAME_WIDTH,  CAMERA_FRAME_WIDTH)
        cap.set(cv2.CAP_PROP_FRAME_HEIGHT, CAMERA_FRAME_HEIGHT)
        cap.set(cv2.CAP_PROP_FPS, 30)
        time.sleep(0.2)
        ok, frame = cap.read()
        if ok and frame is not None:
            print_ts(f"Using camera /dev/video{idx} at "
                     f"{int(cap.get(cv2.CAP_PROP_FRAME_WIDTH))}x"
                     f"{int(cap.get(cv2.CAP_PROP_FRAME_HEIGHT))}")
            return cap
        cap.release()
    return cv2.VideoCapture(-1)

def resize_keep_aspect(frame_bgr: np.ndarray, max_side: int = VISION_MAX_IMAGE_SIDE) -> np.ndarray:
    h, w = frame_bgr.shape[:2]
    longest = max(h, w)
    if longest <= max_side:
        return frame_bgr
    scale = max_side / float(longest)
    return cv2.resize(frame_bgr, (max(1, int(w*scale)), max(1, int(h*scale))), interpolation=cv2.INTER_AREA)

def image_quality_metrics(frame_bgr: np.ndarray) -> dict:
    try:
        gray = cv2.cvtColor(frame_bgr, cv2.COLOR_BGR2GRAY)
        return {"brightness": float(np.mean(gray)), "sharpness": float(cv2.Laplacian(gray, cv2.CV_64F).var())}
    except Exception:
        return {"brightness": 0.0, "sharpness": 0.0}

def denoise_frame(frame_bgr):
    if not VISION_DENOISE_ENABLED: return frame_bgr
    try:
        return cv2.fastNlMeansDenoisingColored(frame_bgr, None, h=VISION_DENOISE_H,
            hColor=VISION_DENOISE_H_COLOR, templateWindowSize=7, searchWindowSize=21)
    except Exception:
        return frame_bgr

def enhance_lighting(frame_bgr):
    if not VISION_LIGHTING_ENHANCE_ENABLED: return frame_bgr
    try:
        lab = cv2.cvtColor(frame_bgr, cv2.COLOR_BGR2LAB)
        l, a, b = cv2.split(lab)
        clahe = cv2.createCLAHE(clipLimit=VISION_CLAHE_CLIP_LIMIT, tileGridSize=(8,8))
        return cv2.cvtColor(cv2.merge((clahe.apply(l), a, b)), cv2.COLOR_LAB2BGR)
    except Exception:
        return frame_bgr

def sharpen_frame(frame_bgr):
    if not VISION_SHARPEN_ENABLED: return frame_bgr
    try:
        blurred = cv2.GaussianBlur(frame_bgr, (0,0), sigmaX=1.0)
        return cv2.addWeighted(frame_bgr, 1.35, blurred, -0.35, 0)
    except Exception:
        return frame_bgr

def crop_largest_face_or_center(frame_bgr):
    h, w = frame_bgr.shape[:2]
    try:
        gray = cv2.cvtColor(frame_bgr, cv2.COLOR_BGR2GRAY)
        cascade = cv2.CascadeClassifier(
            os.path.join(cv2.data.haarcascades, "haarcascade_frontalface_default.xml"))
        faces = cascade.detectMultiScale(gray, scaleFactor=1.1, minNeighbors=4, minSize=(60,60))
        if len(faces) > 0:
            x, y, fw, fh = max(faces, key=lambda b: b[2]*b[3])
            pad = int(max(fw, fh) * 0.65)
            crop = frame_bgr[max(0,y-pad):min(h,y+fh+pad), max(0,x-pad):min(w,x+fw+pad)]
            if crop.size > 0:
                return resize_keep_aspect(crop)
    except Exception:
        pass
    side = min(h, w)
    x1, y1 = (w - side) // 2, (h - side) // 2
    crop = frame_bgr[max(0,y1):y1+side, max(0,x1):x1+side]
    return resize_keep_aspect(crop if crop.size > 0 else frame_bgr)

def preprocess_frame_for_vlm(frame_bgr):
    prep = crop_largest_face_or_center(frame_bgr)
    before = image_quality_metrics(prep)
    prep = denoise_frame(prep)
    prep = enhance_lighting(prep)
    prep = sharpen_frame(prep)
    prep = resize_keep_aspect(prep)
    after = image_quality_metrics(prep)
    return prep, {**{f"before_{k}": v for k,v in before.items()}, **{f"after_{k}": v for k,v in after.items()},
                  "width": float(prep.shape[1]), "height": float(prep.shape[0])}

def is_vlm_image_quality_usable(metrics):
    b = metrics.get("after_brightness", 0.0)
    s = metrics.get("after_sharpness",  0.0)
    if b < VISION_MIN_BRIGHTNESS: return False, f"too dark: {b:.1f}"
    if b > VISION_MAX_BRIGHTNESS: return False, f"too bright: {b:.1f}"
    if s < VISION_MIN_SHARPNESS:  return False, f"too blurry: {s:.1f}"
    return True, "ok"

def save_debug_frame(frame_bgr, prefix="vlm_frame"):
    if not VISION_DEBUG: return None
    try:
        os.makedirs(VISION_DEBUG_DIR, exist_ok=True)
        path = os.path.join(VISION_DEBUG_DIR, f"{prefix}_{datetime.now().strftime('%Y%m%d_%H%M%S_%f')}.jpg")
        cv2.imwrite(path, frame_bgr, [int(cv2.IMWRITE_JPEG_QUALITY), VISION_JPEG_QUALITY])
        return path
    except Exception:
        return None

def encode_frame_for_ollama(frame_bgr):
    try:
        prep, metrics = preprocess_frame_for_vlm(frame_bgr)
        usable, reason = is_vlm_image_quality_usable(metrics)
        if VISION_DEBUG:
            print_ts(f"VLM image quality: {metrics.get('after_brightness',0):.1f}brightness, "
                     f"{metrics.get('after_sharpness',0):.1f}sharpness — {reason}")
            save_debug_frame(prep, "qwen_face_input_clean")
        if not usable:
            return None
        ok, buf = cv2.imencode(".jpg", prep, [int(cv2.IMWRITE_JPEG_QUALITY), VISION_JPEG_QUALITY])
        return base64.b64encode(buf.tobytes()).decode("utf-8") if ok else None
    except Exception as exc:
        print_ts(f"Frame encode failed: {exc}")
        return None

EMOTION_ALIASES = {
    "happy":"joy","happiness":"joy","smile":"joy","smiling":"joy",
    "neutral":"trust","calm":"trust","friendly":"trust","relaxed":"trust",
    "concern":"fear","concerned":"fear","anxious":"fear","anxiety":"fear","afraid":"fear",
    "surprised":"surprise","sad":"sadness","unhappy":"sadness",
    "angry":"anger","mad":"anger","annoyed":"anger",
    "disgusted":"disgust","expectant":"anticipation","curious":"anticipation","thinking":"anticipation",
}

def canonical_emotion_name(name: str) -> Optional[str]:
    cleaned = re.sub(r"[^a-zA-Z]+", "", str(name).strip().lower())
    if cleaned in PLUTCHIK_EMOTIONS: return cleaned
    return EMOTION_ALIASES.get(cleaned)

def normalize_plutchik_scores(raw_data: dict) -> Optional[dict[str, float]]:
    if not isinstance(raw_data, dict): return None
    raw_scores = raw_data.get("scores") if isinstance(raw_data.get("scores"), dict) else raw_data
    scores = {e: 0.0 for e in PLUTCHIK_EMOTIONS}
    if isinstance(raw_scores, dict):
        for key, value in raw_scores.items():
            emotion = canonical_emotion_name(str(key))
            if not emotion: continue
            try: scores[emotion] += max(0.0, float(value))
            except Exception: continue
    total = sum(scores.values())
    if total <= 0:
        dominant = canonical_emotion_name(str(raw_data.get("dominant_emotion", raw_data.get("emotion", ""))))
        if dominant:
            conf = max(0.05, min(1.0, float(raw_data.get("confidence", 0.55))))
            other = max(0.0, 1.0 - conf) / max(1, len(PLUTCHIK_EMOTIONS) - 1)
            return {e: (conf if e == dominant else other) * 100.0 for e in PLUTCHIK_EMOTIONS}
        return None
    return {e: (s * 100.0 if total <= 1.5 else (s / total) * 100.0) for e, s in scores.items()}

def build_qwen_face_prompt() -> str:
    emotions = ", ".join(PLUTCHIK_EMOTIONS.keys())
    return f"""
You are a conservative facial-expression classifier for a human-robot interaction system.

Analyze the visible human face. Use only facial expression, not age, gender, race, or identity.
Map the expression to exactly one of Plutchik's 8 primary emotions: {emotions}

CRITICAL MAPPING RULES — read carefully before assigning:

trust:
  - A relaxed, neutral, or politely attentive face
  - A mild, closed-mouth, or social smile (the kind seen in everyday conversation)
  - A calm, composed expression with no strong emotional activation
  - DEFAULT for any ambiguous or low-intensity expression

joy:
  - A CLEARLY enthusiastic, delighted, or laughing expression
  - Wide open smile showing teeth with raised cheeks and eye crinkles (Duchenne smile)
  - Visibly elevated excitement or happiness — NOT a polite conversational smile
  - Only assign joy when the expression is UNAMBIGUOUSLY positive and strong

anticipation:
  - A concentrated, curious, or thinking face
  - Slightly raised brows with a neutral or mild expression

fear:
  - Wide eyes, tense brow, or visibly startled expression

sadness:
  - Downturned mouth, drooping eyes, or visible distress

anger:
  - Furrowed brow, tightened jaw, or tense aggressive expression

surprise:
  - Raised eyebrows AND open mouth simultaneously

disgust:
  - Nose wrinkle, raised upper lip, or visible aversion

IMPORTANT:
- In a laboratory or conversational setting, most expressions are mild.
- A person simply talking or listening will usually show trust, not joy.
- Do NOT assign joy unless the expression is clearly and strongly joyful.
- When uncertain between joy and trust, ALWAYS choose trust.
- If no face is visible, set dominant_emotion="trust", confidence=0.1, flat scores.

Return JSON only — no markdown, no extra text:
{{
  "dominant_emotion": "joy|trust|fear|surprise|sadness|disgust|anger|anticipation",
  "scores": {{
    "joy": 0.0, "trust": 0.0, "fear": 0.0, "surprise": 0.0,
    "sadness": 0.0, "disgust": 0.0, "anger": 0.0, "anticipation": 0.0
  }},
  "confidence": 0.0,
  "reason": "short explanation referencing specific facial features observed"
}}
""".strip()

def _dampen_reflexive_joy(scores: dict[str, float]) -> dict[str, float]:
    """
    In a laboratory conversational setting, Qwen2.5-VL frequently assigns
    joy > 70% to any smiling face, conflating polite social smiles with
    genuine delight. This post-processor redistributes excess joy probability
    toward trust when the joy score is very high and no other signal is strong.

    Rule: if joy > 0.60 and the second-highest emotion < 0.20,
    redistribute 40% of the excess joy above 0.60 into trust.
    This leaves a clear joy signal intact when it is genuinely strong
    but prevents a 90% joy score from a polite smile dominating the fusion.
    """
    joy = scores.get("joy", 0.0)
    if joy <= 0.60:
        return scores

    ordered = sorted(scores.items(), key=lambda x: x[1], reverse=True)
    second_score = ordered[1][1] if len(ordered) > 1 else 0.0

    if second_score >= 0.20:
        # Second emotion is already meaningful — do not dampen
        return scores

    excess    = joy - 0.60
    transfer  = excess * 0.40        # move 40% of the excess to trust
    new_joy   = joy - transfer
    new_trust = scores.get("trust", 0.0) + transfer

    updated = dict(scores)
    updated["joy"]   = new_joy
    updated["trust"] = new_trust

    # Re-normalise
    total = sum(updated.values())
    return {e: v / total for e, v in updated.items()} if total > 0 else scores


def analyze_frame_emotion_scores(frame_bgr, vision_client) -> Optional[dict[str, float]]:
    image_b64 = encode_frame_for_ollama(frame_bgr)
    if not image_b64: return None
    try:
        resp = vision_client.chat(
            model=VISION_MODEL_NAME, format="json",
            messages=[{"role":"user","content":build_qwen_face_prompt(),"images":[image_b64]}],
            options={"temperature":0.0,"num_predict":220,"num_ctx":2048},
            stream=False,
        )
        raw  = resp.get("message",{}).get("content","")
        if VISION_DEBUG: print_ts(f"Qwen2.5-VL raw: {raw[:300]}")
        data = safe_json_extract(raw)
        if not isinstance(data, dict): return None
        scores = normalize_plutchik_scores(data)
        if not scores: return None

        # Dampen reflexive high-joy scores from polite conversational smiles
        scores = _dampen_reflexive_joy(scores)

        top_e, top_s = max(scores.items(), key=lambda x: x[1])
        if top_s < FACE_MIN_TOP_SCORE:
            print_ts(f"Qwen result rejected (weak): {top_e}={top_s:.1f}%")
            return None
        return scores
    except Exception as exc:
        print_ts(f"Qwen2.5-VL failed: {exc}")
        return None


class FaceEmotionSampler:
    def __init__(self, camera_device, vision_client):
        self.camera_device   = camera_device
        self.vision_client   = vision_client
        self.cap             = None
        self.window_created  = False
        self.started_at      = now_ts()
        self.error           = None
        self.emotion_score_samples: list[dict[str, float]] = []
        self.frame_count     = 0
        self.sampled_frame_count = 0
        self.capture_start_time  = None
        self.last_sample_time    = 0.0
        self.last_status         = "warming up..."
        self.snapshot_frame      = None
        self.snapshot_taken_at   = None

    def start(self):
        self.started_at = now_ts()
        self.capture_start_time = time.time()
        self.cap = open_camera(self.camera_device)
        if not self.cap.isOpened():
            self.error = "Could not open camera."
            self.cap.release()
            self.cap = None
            return
        if CAMERA_PREVIEW_ENABLED:
            try:
                cv2.namedWindow(CAMERA_PREVIEW_WINDOW_NAME, cv2.WINDOW_NORMAL)
                self.window_created = True
            except Exception as exc:
                self.error = f"Preview could not start: {exc}"

    def _draw_preview(self, frame):
        if not (CAMERA_PREVIEW_ENABLED and self.window_created): return
        try:
            pf = frame.copy()
            cv2.putText(pf, "Recording speech...", (20,35), cv2.FONT_HERSHEY_SIMPLEX, 0.8, (0,255,0), 2, cv2.LINE_AA)
            cv2.putText(pf, f"Emotion: {self.last_status}", (20,70), cv2.FONT_HERSHEY_SIMPLEX, 0.7, (255,255,255), 2, cv2.LINE_AA)
            cv2.imshow(CAMERA_PREVIEW_WINDOW_NAME, cv2.resize(pf, (CAMERA_PREVIEW_WIDTH, CAMERA_PREVIEW_HEIGHT)))
            cv2.waitKey(1)
        except Exception as exc:
            self.error = f"Preview failed: {exc}"

    def sample_if_due(self):
        if self.cap is None or self.capture_start_time is None: return
        ok, frame = self.cap.read()
        if not ok or frame is None: return
        frame = normalize_camera_frame(frame)
        self.frame_count += 1
        elapsed = time.time() - self.capture_start_time
        self._draw_preview(frame)
        if elapsed >= CAMERA_WARMUP_SECONDS and self.snapshot_frame is None:
            self.snapshot_frame    = frame.copy()
            self.snapshot_taken_at = now_ts()
            self.sampled_frame_count = 1
            self.last_status = "snapshot captured"
            print_ts("Facial snapshot captured; Qwen analysis deferred to speech end.")

    def _analyze_snapshot_now(self):
        if self.snapshot_frame is None:
            self.last_status = "no snapshot"
            return
        print_ts("Analyzing facial snapshot with Qwen2.5-VL...")
        scores = analyze_frame_emotion_scores(self.snapshot_frame, self.vision_client)
        if not scores:
            self.last_status = "no reliable VLM result"
            return
        top_e, top_s = max(scores.items(), key=lambda x: x[1])
        if top_s < FACE_MIN_TOP_SCORE:
            self.last_status = f"weak: {top_e}={top_s:.0f}%"
            return
        self.emotion_score_samples.append(scores)
        self.last_status = f"{top_e}: {top_s:.0f}%"
        print_ts(f"Qwen2.5-VL accepted: {self.last_status}")

    def finish(self) -> FaceEmotionCapture:
        if self.cap is not None:
            self.cap.release(); self.cap = None
        if self.window_created:
            try: cv2.destroyWindow(CAMERA_PREVIEW_WINDOW_NAME); cv2.waitKey(1)
            except Exception: pass
        try:
            self._analyze_snapshot_now()
        except Exception as exc:
            self.error = f"Qwen2.5-VL analysis failed: {exc}"
            print_ts(self.error)
        return FaceEmotionCapture(
            emotion_score_samples=self.emotion_score_samples,
            frame_count=self.frame_count,
            sampled_frame_count=self.sampled_frame_count,
            started_at=self.started_at,
            ended_at=now_ts(),
            error=self.error,
        )


