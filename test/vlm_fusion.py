@dataclass
class EmotionResult:
    """Backward-compatible single-label emotion result for response generation."""
    emotion:    str
    confidence: float
    reason:     str


@dataclass
class TranscriptionResult:
    """ASR output with quality signals for linguistic reliability scoring."""
    text:             str
    word_confidences: list[float]   # per-word probability from faster-whisper
    no_speech_prob:   float         # mean segment-level no-speech probability
    avg_logprob:      float = -1.0  # mean segment-level log-probability


@dataclass
class ProsodyFeatures:
    """Acoustic feature vector extracted by librosa."""
    f0_mean:          float   # mean voiced fundamental frequency (Hz)
    f0_std:           float   # F0 variability (indicates emotional arousal)
    rms_energy:       float   # mean RMS energy (speech loudness)
    speaking_rate:    float   # onset events per second (syllable proxy)
    zcr_mean:         float   # zero-crossing rate
    voiced_ratio:     float   # proportion of voiced frames in the utterance
    duration_seconds: float


@dataclass
class ModalityEmotionResult:
    """
    Per-modality output for the fusion module.
    probs: probability distribution over Plutchik's 8 emotions (sums to 1.0).
    reliability: scalar in [0, 1] computed from observable quality signals.
    """
    probs:       dict[str, float]
    reliability: float
    modality:    str   # "linguistic" | "acoustic" | "visual"


@dataclass
class FusedEmotionResult:
    """
    Output of the adaptive reliability-aware late fusion module.
    Wraps both the final label and the full internal state for logging.
    """
    emotion:     str
    confidence:  float
    probs:       dict[str, float]
    weights:     dict[str, float]   # effective normalised weights: L, A, V
    raw_weights: dict[str, float]   # raw reliability scores before normalisation
    reason:      str
    linguistic:  Optional[ModalityEmotionResult]
    acoustic:    Optional[ModalityEmotionResult]
    visual:      Optional[ModalityEmotionResult]


@dataclass
class FaceEmotionCapture:
    emotion_score_samples: list[dict[str, float]]
    frame_count:           int
    sampled_frame_count:   int
    started_at:            str
    ended_at:              str
    error:                 Optional[str] = None

    @property
    def averaged_scores(self) -> dict[str, float]:
        if not self.emotion_score_samples:
            return {}
        totals: dict[str, float] = {}
        for sample in self.emotion_score_samples:
            for emotion, score in sample.items():
                totals[emotion] = totals.get(emotion, 0.0) + score
        count = len(self.emotion_score_samples)
        return {emotion: total / count for emotion, total in totals.items()}

    @property
    def dominant_emotion(self) -> Optional[str]:
        scores = self.averaged_scores
        if not scores:
            return None
        return max(scores.items(), key=lambda item: item[1])[0]

    @property
    def is_reliable(self) -> bool:
        scores = self.averaged_scores
        if not scores:
            return False
        ordered = sorted(scores.items(), key=lambda item: item[1], reverse=True)
        top_score   = ordered[0][1]
        second_score = ordered[1][1] if len(ordered) > 1 else 0.0
        return top_score >= FACE_MIN_TOP_SCORE and (top_score - second_score) >= FACE_MIN_MARGIN

    @property
    def summary_text(self) -> str:
        if self.error:
            return f"No facial-expression hint available because: {self.error}"
        scores = self.averaged_scores
        if not scores:
            return "No reliable facial-expression hint was captured during speech."
        ordered = sorted(scores.items(), key=lambda item: item[1], reverse=True)
        if not self.is_reliable:
            top_parts = [f"{emo}={score:.0f}%" for emo, score in ordered[:3]]
            return (
                "Facial-expression hint was weak or mixed; "
                f"top_signals=({', '.join(top_parts)}); "
                f"samples={self.sampled_frame_count}"
            )
        parts = [f"{emo}={score:.0f}%" for emo, score in ordered if score >= 5.0]
        return (
            f"dominant={self.dominant_emotion}; "
            f"averaged_scores=({', '.join(parts)}); "
            f"samples={self.sampled_frame_count}"
        )

    @property
    def as_json(self) -> dict:
        scores = self.averaged_scores
        return {
            "available":       self.error is None and bool(scores),
            "reliable":        self.is_reliable,
            "dominant_emotion": self.dominant_emotion,
            "averaged_scores": scores,
            "frame_count":     self.frame_count,
            "sampled_frame_count": self.sampled_frame_count,
            "started_at":      self.started_at,
            "ended_at":        self.ended_at,
            "error":           self.error,
            "note": (
                "Qwen2.5-VL facial expression analysis is a weak supporting signal. "
                "Fusion weights are computed dynamically from reliability scores."
            ),
        }


