# Legacy single-label emotion detection  (kept for fallback / compat)
# ══════════════════════════════════════════════════════════════════════════════

def simple_emotion_fallback(transcribed_text: str) -> Optional[EmotionResult]:
    text = transcribed_text.strip().lower()
    greetings = {"hello","hi","hey","good morning","good afternoon","good evening"}
    farewells  = {"bye","goodbye","see you","see you later","talk later","have a good day","have a nice day"}
    if text.rstrip(".!?") in greetings:
        return EmotionResult("trust", 0.6, "Friendly social opening.")
    if any(p in text for p in farewells):
        return EmotionResult("trust", 0.7, "Polite farewell.")
    if any(p in text for p in ["today's date","todays date","what is the date"]):
        return EmotionResult("anticipation", 0.5, "User requesting date information.")
    return None

def detect_emotion(client, transcribed_text, facial_emotion_hint=None) -> EmotionResult:
    """Legacy single-label fallback. Use build_linguistic_modal for fusion pipeline."""
    fallback = simple_emotion_fallback(transcribed_text)
    if fallback: return fallback
    emotions = ", ".join(PLUTCHIK_EMOTIONS.keys())
    facial_s = f"Facial hint: {facial_emotion_hint}\n" if facial_emotion_hint else ""
    prompt = f"""
Classify the user's emotion. Return JSON:
{{"emotion": "one of: {emotions}", "confidence": 0.0, "reason": "explanation"}}

Rules: confidence 0-1. For greetings → trust. For farewells → trust. No markdown.
User text: {transcribed_text}
{facial_s}""".strip()
    try:
        resp = client.chat(model=MODEL_NAME, format="json",
            messages=[{"role":"system","content":"Return valid JSON only."},
                      {"role":"user","content":prompt}],
            options={"temperature":0.1,"num_predict":120,"num_ctx":2048}, stream=False)
        data = safe_json_extract(resp["message"]["content"])
        if not data: return EmotionResult("trust", 0.3, "Parse failure fallback.")
        emotion = str(data.get("emotion","")).strip().lower()
        if emotion not in PLUTCHIK_EMOTIONS: emotion = "trust"
        return EmotionResult(emotion, max(0.0, min(1.0, float(data.get("confidence",0.0)))),
                             str(data.get("reason","")))
    except Exception:
        return EmotionResult("trust", 0.3, "LLM error fallback.")


